SELECT
    L.NULOG,
    CASE
        WHEN FINDEV.NUCOMPENS IS NOT NULL THEN 'COMPENSADO'
        WHEN RAV.CODUSU IS NOT NULL THEN 'VISUALIZADO'
        ELSE L.STATUS
    END AS STATUS,
    L.NUNOTADEV,
    L.NUMNOTADEV,
    L.NUNOTAORIG,
    L.NUMNOTAORIG,
    FINDEV.NUCOMPENS AS NUCOMPENS_DEV,
    FINORIG.NUCOMPENS AS NUCOMPENS_ORIG,
    L.CODEMP,
    L.CODPARC,
    PAR.NOMEPARC,
    L.CODUSURESPFIN,
    USURESP.NOMEUSU AS NOME_RESP_FINANCEIRO,
    L.NUAVISO,
    L.DHAVISO,
    NVL(L.CODUSUVISUALIZOU, RAV.CODUSU) AS CODUSUVISUALIZOU,
    USUVIS.NOMEUSU AS NOME_USU_VISUALIZOU,
    L.DHVISUALIZACAO,
    L.DHCOMPENSACAO,
    L.OBSERVACAO
FROM AD_LOGCOMPDEV L
LEFT JOIN (
    SELECT NUNOTA, MAX(NUCOMPENS) AS NUCOMPENS
      FROM TGFFIN
     WHERE NUCOMPENS IS NOT NULL
     GROUP BY NUNOTA
) FINDEV
       ON FINDEV.NUNOTA = L.NUNOTADEV
LEFT JOIN (
    SELECT NUNOTA, MAX(NUCOMPENS) AS NUCOMPENS
      FROM TGFFIN
     WHERE NUCOMPENS IS NOT NULL
     GROUP BY NUNOTA
) FINORIG
       ON FINORIG.NUNOTA = L.NUNOTAORIG
LEFT JOIN (
    SELECT NUAVISO, MIN(CODUSU) AS CODUSU
      FROM TSIRAV
     GROUP BY NUAVISO
) RAV
       ON RAV.NUAVISO = L.NUAVISO
LEFT JOIN TGFPAR PAR
       ON PAR.CODPARC = L.CODPARC
LEFT JOIN TSIUSU USURESP
       ON USURESP.CODUSU = L.CODUSURESPFIN
LEFT JOIN TSIUSU USUVIS
       ON USUVIS.CODUSU = NVL(L.CODUSUVISUALIZOU, RAV.CODUSU)
WHERE (
    L.STATUS IN ('PENDENTE', 'AVISADO', 'VISUALIZADO', 'FECHADO')
    OR FINDEV.NUCOMPENS IS NOT NULL
)
ORDER BY
    CASE
        WHEN FINDEV.NUCOMPENS IS NOT NULL THEN 5
        WHEN RAV.CODUSU IS NOT NULL THEN 3
        WHEN L.STATUS = 'PENDENTE' THEN 1
        WHEN L.STATUS = 'AVISADO' THEN 2
        WHEN L.STATUS = 'VISUALIZADO' THEN 3
        WHEN L.STATUS = 'FECHADO' THEN 4
        ELSE 9
    END,
    NVL(L.DHCOMPENSACAO, L.DHAVISO) DESC,
    L.NULOG DESC;
