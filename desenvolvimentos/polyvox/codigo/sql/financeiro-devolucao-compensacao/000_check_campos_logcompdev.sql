SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'AD_LOGCOMPDEV'
ORDER BY COLUMN_ID;

SELECT
    CASE
        WHEN COUNT(*) = 17 THEN 'OK'
        ELSE 'FALTAM CAMPOS'
    END AS STATUS_CAMPOS,
    COUNT(*) AS QTD_CAMPOS_ENCONTRADOS
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'AD_LOGCOMPDEV'
  AND COLUMN_NAME IN (
      'NULOG',
      'NUNOTADEV',
      'NUMNOTADEV',
      'NUNOTAORIG',
      'NUMNOTAORIG',
      'CODEMP',
      'CODPARC',
      'CODUSURESPFIN',
      'NUAVISO',
      'DHAVISO',
      'CODUSUVISUALIZOU',
      'DHVISUALIZACAO',
      'DHCOMPENSACAO',
      'STATUS',
      'OBSERVACAO',
      'DHCRIACAO',
      'DHALTERACAO'
  );
