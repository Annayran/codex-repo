CREATE TABLE AD_LOGCOMPDEV (
    NULOG              NUMBER(10)     NOT NULL,
    NUNOTADEV          NUMBER(10)     NOT NULL,
    NUMNOTADEV         NUMBER(10),
    NUNOTAORIG         NUMBER(10)     NOT NULL,
    NUMNOTAORIG        NUMBER(10),
    CODEMP             NUMBER(5),
    CODPARC            NUMBER(10),
    CODUSURESPFIN      NUMBER(10),
    NUAVISO            NUMBER(10),
    DHAVISO            DATE,
    CODUSUVISUALIZOU   NUMBER(10),
    DHVISUALIZACAO     DATE,
    DHCOMPENSACAO      DATE,
    STATUS             VARCHAR2(20)   DEFAULT 'PENDENTE' NOT NULL,
    OBSERVACAO         VARCHAR2(4000),
    DHCRIACAO          DATE           DEFAULT SYSDATE NOT NULL,
    DHALTERACAO        DATE,
    CONSTRAINT PK_AD_LOGCOMPDEV PRIMARY KEY (NULOG),
    CONSTRAINT CK_AD_LOGCOMPDEV_STATUS CHECK (STATUS IN (
        'PENDENTE',
        'AVISADO',
        'VISUALIZADO',
        'FECHADO',
        'COMPENSADO',
        'CANCELADO'
    ))
);

CREATE INDEX IX_AD_LOGCOMPDEV_DEV ON AD_LOGCOMPDEV (NUNOTADEV);
CREATE INDEX IX_AD_LOGCOMPDEV_ORIG ON AD_LOGCOMPDEV (NUNOTAORIG);
CREATE INDEX IX_AD_LOGCOMPDEV_AVISO ON AD_LOGCOMPDEV (NUAVISO);
CREATE INDEX IX_AD_LOGCOMPDEV_STATUS ON AD_LOGCOMPDEV (STATUS);

COMMENT ON TABLE AD_LOGCOMPDEV IS
    'Log de avisos e compensações financeiras entre nota de devolução e nota de origem.';

COMMENT ON COLUMN AD_LOGCOMPDEV.NUNOTADEV IS
    'NUNOTA da nota de devolução.';

COMMENT ON COLUMN AD_LOGCOMPDEV.NUNOTAORIG IS
    'NUNOTA da nota de origem vinculada à devolução.';

COMMENT ON COLUMN AD_LOGCOMPDEV.NUAVISO IS
    'Aviso gerado em TSIAVI para o responsável financeiro.';

COMMENT ON COLUMN AD_LOGCOMPDEV.CODUSUVISUALIZOU IS
    'Usuário que visualizou o aviso/pop-up.';
