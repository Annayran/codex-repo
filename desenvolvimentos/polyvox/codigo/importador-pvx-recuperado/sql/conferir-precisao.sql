SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE
FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME = 'AD_IMPREGPED' AND COLUMN_NAME IN ('QTY','UNITPRICE','TOTALPRICE'))
   OR (TABLE_NAME = 'TGFITE' AND COLUMN_NAME IN ('QTDNEG','VLRUNIT','VLRUNITMOE','VLRTOT','VLRTOTMOE'))
ORDER BY TABLE_NAME, COLUMN_NAME;

