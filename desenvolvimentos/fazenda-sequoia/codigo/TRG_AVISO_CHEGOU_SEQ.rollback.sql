CREATE OR REPLACE TRIGGER TRG_AVISO_CHEGOU_SEQ
AFTER UPDATE OF STATUSNOTA ON TGFCAB
FOR EACH ROW
WHEN (NEW.STATUSNOTA = 'L'
      AND NVL(OLD.STATUSNOTA, 'X') <> 'L'
      AND NEW.CODTIPOPER IN (1400, 1401))
DECLARE
  V_NUAVISO   TSIAVI.NUAVISO%TYPE;
  V_TITULO    TSIAVI.TITULO%TYPE;
  V_DESCRICAO VARCHAR2(4000) := '<b>Chegouu!</b><br>';
  V_EXISTE    NUMBER;
BEGIN
  -- Lista de produtos da nota, um por linha
  FOR R IN (SELECT DISTINCT I.CODPROD, P.DESCRPROD
              FROM TGFITE I
              JOIN TGFPRO P ON P.CODPROD = I.CODPROD
             WHERE I.NUNOTA = :NEW.NUNOTA
             ORDER BY I.CODPROD) LOOP
    V_DESCRICAO := V_DESCRICAO || R.CODPROD || ' - ' || R.DESCRPROD || '<br>';
    EXIT WHEN LENGTH(V_DESCRICAO) > 1900;
  END LOOP;

  SELECT NVL(MAX(NOMEUSU), 'SISTEMA')
    INTO V_TITULO
    FROM TSIUSU
   WHERE CODUSU = :NEW.CODUSU;

  -- Próximo número pelo contador do Sankhya, pulando números já usados
  LOOP
    UPDATE TGFNUM
       SET ULTCOD = ULTCOD + 1
     WHERE ARQUIVO = 'TSIAVI' AND CODEMP = 1
    RETURNING ULTCOD INTO V_NUAVISO;

    SELECT COUNT(*) INTO V_EXISTE FROM TSIAVI WHERE NUAVISO = V_NUAVISO;
    EXIT WHEN V_EXISTE = 0;
  END LOOP;

  INSERT INTO TSIAVI (NUAVISO, TITULO, DESCRICAO, IDENTIFICADOR, IMPORTANCIA,
                      CODUSU, CODGRUPO, TIPO, DHCRIACAO, CODUSUREMETENTE)
  VALUES (V_NUAVISO, V_TITULO, SUBSTR(V_DESCRICAO, 1, 2000), 'PERSONALIZADO', 3,
          NULL, NULL, 'P', SYSDATE, NVL(:NEW.CODUSU, 0));
END;
