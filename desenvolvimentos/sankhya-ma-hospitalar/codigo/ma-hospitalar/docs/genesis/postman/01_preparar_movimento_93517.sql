-- Somente leitura. Preenche as variaveis da colecao Postman para o caso 93517/13482/serie 400.
SELECT
    V.CHAVE_MOVIMENTO,
    V.CODEMP,
    V.NUNOTA,
    V.NUMNOTA,
    V.SEQUENCIA,
    V.CODPARC,
    V.CODPROD,
    V.SERIE,
    V.CNPJ_CPF_PARCEIRO AS CLIENTE_DOCUMENTO,
    V.NOMEPARC AS CLIENTE_NOME_FANTASIA,
    V.RAZAO_PARCEIRO AS CLIENTE_RAZAO_SOCIAL,
    V.ENDERECO AS CLIENTE_ENDERECO,
    REGEXP_REPLACE(TO_CHAR(V.CEP), '[^0-9]', '') AS CLIENTE_CEP,
    REGEXP_REPLACE(TO_CHAR(V.TELEFONE), '[^0-9]', '') AS CLIENTE_TELEFONE,
    V.DESCRLOCAL AS LOCALIZACAO,
    V.PODER,
    V.TIPO AS MOVIMENTO,
    V.STATUS_ESTOQUE_DESC AS STATUS_ESTOQUE,
    V.GARANTIA_MESES,
    V.MARCA,
    V.VLRUNIT AS VALOR_UNITARIO,
    V.DTNEG,
    ROUND((CAST(V.DTNEG AS DATE) - DATE '1970-01-01') * 86400000) AS EPOCH_MS_REFERENCIA,
    C.IDGENESIS AS CLIENTE_ID_LOCAL,
    C.CODIGOEXTERNO AS CLIENTE_CODIGO_EXTERNO,
    S.IDGENESIS AS SETOR_ID_LOCAL,
    S.CODIGOEXTERNO AS SETOR_CODIGO_EXTERNO,
    M.IDGENESIS AS MODELO_ID_LOCAL,
    M.CODIGOEXTERNO AS MODELO_CODIGO_EXTERNO,
    I.IDGENESIS AS ITEM_ID_LOCAL,
    I.CODIGOEXTERNO AS ITEM_CODIGO_EXTERNO
FROM AD_VW_GENESIS_ESTOQUE V
LEFT JOIN AD_GENCLIENTE C
       ON C.IDBASE = 1
      AND C.CODPARC = V.CODPARC
LEFT JOIN AD_GENSECTOR S
       ON S.IDBASE = 1
      AND S.CODPARC = V.CODPARC
LEFT JOIN AD_GENMODELO M
       ON M.IDBASE = 1
      AND M.CODPROD = V.CODPROD
LEFT JOIN AD_GENITEMMAT I
       ON I.IDBASE = 1
      AND I.CODPROD = V.CODPROD
      AND UPPER(TRIM(I.SERIE)) = UPPER(TRIM(V.SERIE))
WHERE V.NUNOTA = 93517
  AND V.CODPROD = 13482
  AND UPPER(TRIM(V.SERIE)) = '400';

