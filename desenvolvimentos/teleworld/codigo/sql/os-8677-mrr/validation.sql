SELECT TIPO, NUMCONTRATO, CODPROD, CODOCOR, DTOCOR,
       AD_CLASSIFICACAO, VLR, VLR_CAN
FROM VW_ZAYA_EVOLUCAO_MRR
WHERE CODPROD = 1048
  AND CODOCOR = 14
  AND ((NUMCONTRATO = 338 AND DTOCOR >= DATE '2026-07-02' AND DTOCOR < DATE '2026-07-03')
    OR (NUMCONTRATO = 627 AND DTOCOR >= DATE '2026-09-01' AND DTOCOR < DATE '2026-09-02'))
ORDER BY NUMCONTRATO, TIPO;
