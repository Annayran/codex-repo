-- 1. Repeticoes na view atualmente instalada. Nao elimina linhas.
SELECT TIPO, NUMCONTRATO, CODPROD, CODOCOR, DTOCOR,
       AD_CLASSIFICACAO, VLR, VLR_CAN, COUNT(*) AS REPETICOES
FROM VW_ZAYA_EVOLUCAO_MRR
WHERE NUMCONTRATO IN (328,338,627)
GROUP BY TIPO, NUMCONTRATO, CODPROD, CODOCOR, DTOCOR,
         AD_CLASSIFICACAO, VLR, VLR_CAN
HAVING COUNT(*) > 1
ORDER BY NUMCONTRATO, CODPROD, DTOCOR, TIPO;

-- 2. Quantidade de precos por contrato/produto: fator do JOIN PRE2 sem filtro.
SELECT NUMCONTRATO, CODPROD, COUNT(*) AS QTD_PRECOS
FROM TCSPRE
WHERE NUMCONTRATO IN (328,338,627)
GROUP BY NUMCONTRATO, CODPROD
ORDER BY NUMCONTRATO, CODPROD;

-- 3. Historico de precos para conferir os deltas, sem dados de parceiro.
SELECT NUMCONTRATO, CODPROD, REFERENCIA, VALOR
FROM TCSPRE
WHERE NUMCONTRATO IN (328,338,627)
ORDER BY NUMCONTRATO, CODPROD, REFERENCIA;
