SELECT
    /* Controle da revisão: manter no início da grade */
    COM.AD_REVISADO AS AD_REVISADO,
    CASE
        WHEN NVL(COM.AD_REVISADO, 'N') = 'S'
            THEN 'Revisada'
        ELSE 'Pendente'
    END AS STATUS_REVISAO,
    REV.NOMEUSU AS NOME_REVISOR,
    COM.AD_DHREV AS AD_DHREV,

    CASE
        WHEN NVL(COM.AD_REVISADO, 'N') = 'S'
            THEN '#28A745'
        ELSE '#DC3545'
    END AS FAROL_REVISAO,

    /* Mesma ordem funcional da tela Fechamento de Comissões */
    VCOM.NOMEPARC AS NOMEPARC,
    VCOM.COMISSAO AS COMISSAO,
    VCOM.PERCCOM AS PERCCOM,
    VCOM.VLRBAIXA AS VLRBAIXA,
    VCOM.NUMNOTA AS NUMNOTA,
    VCOM.NUNOTA AS NUNOTA,
    VCOM.COMLIQ AS COMLIQ,
    VCOM.VLRCOM AS VLRCOM,
    VCOM.COMLIQ AS COMISSAO_PARCELA,
    VCOM.DESCROPER AS DESCROPER,
    VCOM.FINNUFIN AS FINNUFIN,
    VCOM.DESCRFORM AS DESCRFORM,
    VCOM.VLRDESDOB AS VLRDESDOB,
    VCOM.DHBAIXA AS DHBAIXA,
    COM.CODVEND AS CODVEND,
    VCOM.APELIDO AS APELIDO,
    COM.NUNOTAORIG AS NUNOTAORIG,
    VCOM.CODEMP AS CODEMP,
    EMP.NOMEFANTASIA AS NOMEFANTASIA,
    VCOM.CODPARC AS CODPARC,
    VCOM.CODPARCVEN AS CODPARCVEN,
    COM.TIPO AS TIPO,
    VCOM.VLRDESC AS VLRDESC,
    VCOM.DESCRNAT AS DESCRNAT,
    NVL(OPC_TIPCALC.OPCAO, VCOM.TIPCALC) AS TIPCALC_DESCRICAO,
    VCOM.DESDOBRAMENTO AS DESDOBRAMENTO,
    VCOM.DTVENC AS DTVENC,
    VCOM.CODTIPTIT AS CODTIPTIT,
    VCOM.DHCONCILIACAO AS DHCONCILIACAO,
    VCOM.NOSSONUM AS NOSSONUM,
    VCOM.DTNEG AS DTNEG,
    VCOM.DTFATUR AS DTFATUR,
    VCOM.CODTIPVENDA AS CODTIPVENDA,
    COM.NUMOSORIG AS NUMOSORIG,
    COM.NUMITEMORIG AS NUMITEMORIG,
    NVL(OPC_TIPMOV.OPCAO, VCOM.TIPMOV) AS TIPMOV_DESCRICAO,
    COM.NUFINORIG AS NUFINORIG,
    VCOM.TAXA AS TAXA,
    VCOM.CODEVENTO AS CODEVENTO,
    VCOM.TIPINTEGRA AS TIPINTEGRA,
    COM.CODFORM AS CODFORM,
    VCOM.INICEXEC AS INICEXEC,
    VCOM.DTMOV AS DTMOV,
    VCOM.CODCENCUSPAD AS CODCENCUSPAD,
    NVL(OPC_RECDESP.OPCAO, TO_CHAR(FIN.RECDESP)) AS RECDESP_DESCRICAO,

    /* Campos técnicos: manter no SELECT e ocultar na grade */
    :PERIODO.INI AS PERIODO_INI,
    :PERIODO.FIN AS PERIODO_FIN,
    COM.NUFIN AS NUFIN,
    COM.AD_CODUSUREV AS AD_CODUSUREV,
    REV.EMAIL AS EMAIL_USUARIO_REVISOR,
    VCOM.POSICAO_QUERY AS POSICAO_QUERY,
    VCOM.TIPFATSERV AS TIPFATSERV

FROM VGFCOM_FECH VCOM

INNER JOIN TGFCOM COM
    ON COM.CODVEND = VCOM.CODVEND
   AND NVL(COM.NUNOTAORIG, -1)
       = NVL(VCOM.NUNOTAORIG, -1)
   AND NVL(COM.NUFINORIG, -1)
       = NVL(VCOM.NUFINORIG, -1)
   AND NVL(COM.NUMOSORIG, -1)
       = NVL(VCOM.NUMOSORIG, -1)
   AND NVL(COM.NUMITEMORIG, -1)
       = NVL(VCOM.NUMITEMORIG, -1)
   AND NVL(COM.TIPO, '#')
       = NVL(VCOM.TIPO, '#')
   AND NVL(COM.CODFORM, -1)
       = NVL(VCOM.CODFORM, -1)

LEFT JOIN TSIEMP EMP
    ON EMP.CODEMP = VCOM.CODEMP

LEFT JOIN TGFFIN FIN
    ON FIN.NUFIN = VCOM.FINNUFIN

LEFT JOIN TGFPAR PAR
    ON PAR.CODPARC = VCOM.CODPARC

LEFT JOIN TGFVEN VEN
    ON VEN.CODVEND = VCOM.CODVEND

LEFT JOIN TSIUSU REV
    ON REV.CODUSU = COM.AD_CODUSUREV

LEFT JOIN (
    SELECT
        OPC.VALOR,
        MAX(OPC.OPCAO) AS OPCAO
    FROM TDDCAM CAM
    INNER JOIN TDDOPC OPC
        ON OPC.NUCAMPO = CAM.NUCAMPO
    WHERE CAM.NOMETAB = 'TGFVEN'
      AND CAM.NOMECAMPO = 'TIPCALC'
    GROUP BY OPC.VALOR
) OPC_TIPCALC
    ON OPC_TIPCALC.VALOR = VCOM.TIPCALC

LEFT JOIN (
    SELECT
        OPC.VALOR,
        MAX(OPC.OPCAO) AS OPCAO
    FROM TDDCAM CAM
    INNER JOIN TDDOPC OPC
        ON OPC.NUCAMPO = CAM.NUCAMPO
    WHERE CAM.NOMETAB = 'TGFCAB'
      AND CAM.NOMECAMPO = 'TIPMOV'
    GROUP BY OPC.VALOR
) OPC_TIPMOV
    ON OPC_TIPMOV.VALOR = VCOM.TIPMOV

LEFT JOIN (
    SELECT
        OPC.VALOR,
        MAX(OPC.OPCAO) AS OPCAO
    FROM TDDCAM CAM
    INNER JOIN TDDOPC OPC
        ON OPC.NUCAMPO = CAM.NUCAMPO
    WHERE CAM.NOMETAB = 'TGFFIN'
      AND CAM.NOMECAMPO = 'RECDESP'
    GROUP BY OPC.VALOR
) OPC_RECDESP
    ON OPC_RECDESP.VALOR = TO_CHAR(FIN.RECDESP)

WHERE
(
    (
        VCOM.DTNEG
            BETWEEN :PERIODO.INI AND :PERIODO.FIN
        AND VCOM.POSICAO_QUERY = '1'
    )

    OR

    (
        (
            (
                VCOM.TIPCALC = 'N'
                AND VCOM.DTNEG
                    BETWEEN :PERIODO.INI AND :PERIODO.FIN
            )
            OR
            (
                VCOM.DHBAIXA
                    BETWEEN :PERIODO.INI AND :PERIODO.FIN
            )
        )
        AND VCOM.POSICAO_QUERY = '2'
    )

    OR

    (
        VCOM.DHBAIXA
            BETWEEN :PERIODO.INI AND :PERIODO.FIN
        AND VCOM.POSICAO_QUERY IN ('3', '4', '5', '6')
    )

    OR

    (
        (
            VCOM.DHBAIXA
                BETWEEN :PERIODO.INI AND :PERIODO.FIN
            OR
            (
                VCOM.TIPFATSERV IN ('S', 'U')
                AND VCOM.DHBAIXA < :PERIODO.INI
                AND VCOM.INICEXEC
                    BETWEEN :PERIODO.INI AND :PERIODO.FIN
            )
        )
        AND VCOM.POSICAO_QUERY IN ('7', '8')
    )
)

AND VCOM.CODVEND = :CODVEND

ORDER BY
    COM.CODVEND,
    COM.CODFORM,
    COM.NUNOTAORIG,
    VCOM.COMLIQ,
    COM.TIPO
