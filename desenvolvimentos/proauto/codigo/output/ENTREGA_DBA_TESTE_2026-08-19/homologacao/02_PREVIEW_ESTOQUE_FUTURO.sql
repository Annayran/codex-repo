WITH FUTURO AS (
    SELECT ITE.CODPROD,
           SUM(GREATEST(NVL(ITE.QTDNEG, 0) - NVL(ITE.QTDENTREGUE, 0), 0)) AS QTDFUTURA
      FROM TGFITE ITE
      JOIN TGFCAB CAB
        ON CAB.NUNOTA = ITE.NUNOTA
     WHERE CAB.TIPMOV = 'C'
       AND CAB.STATUSNOTA = 'L'
       AND ITE.PENDENTE = 'S'
     GROUP BY ITE.CODPROD
)
SELECT FILA.CODPROD,
       COUNT(*) AS POSICOES_ATIVAS,
       MAX(FNC_ESTCOMERCIAL_PRA(FILA.CODPROD)) AS ESTOQUE_ATUAL,
       MAX(NVL(FUT.QTDFUTURA, 0)) AS ESTOQUE_FUTURO,
       MAX(FNC_ESTCOMERCIAL_PRA(FILA.CODPROD) + NVL(FUT.QTDFUTURA, 0)) AS COBERTURA_PROJETADA,
       SUM(FILA.QTDPENDENTE) AS RESERVA_PENDENTE
  FROM AD_VGFRESEST FILA
  LEFT JOIN FUTURO FUT
    ON FUT.CODPROD = FILA.CODPROD
 GROUP BY FILA.CODPROD
 ORDER BY FILA.CODPROD;

-- Cobertura projetada da fila provisionada, descontando antes a fila ativa.
WITH FUTURO AS (
    SELECT ITE.CODPROD,
           SUM(GREATEST(NVL(ITE.QTDNEG, 0) - NVL(ITE.QTDENTREGUE, 0), 0)) AS QTDFUTURA
      FROM TGFITE ITE
      JOIN TGFCAB CAB
        ON CAB.NUNOTA = ITE.NUNOTA
     WHERE CAB.TIPMOV = 'C'
       AND CAB.STATUSNOTA = 'L'
       AND ITE.PENDENTE = 'S'
     GROUP BY ITE.CODPROD
),
ATIVA AS (
    SELECT CODPROD,
           SUM(QTDPENDENTE) AS QTDATIVA
      FROM AD_VGFRESEST
     GROUP BY CODPROD
),
PROVISIONADA AS (
    SELECT CODPROD,
           SUM(QTDPENDENTE) AS QTDPROVISIONADA
      FROM AD_VGFPROVEST
     GROUP BY CODPROD
)
SELECT PROV.CODPROD,
       FNC_ESTCOMERCIAL_PRA(PROV.CODPROD) AS ESTOQUE_ATUAL,
       NVL(FUT.QTDFUTURA, 0) AS ESTOQUE_FUTURO,
       NVL(ATV.QTDATIVA, 0) AS FILA_ATIVA,
       PROV.QTDPROVISIONADA AS FILA_PROVISIONADA,
       FNC_ESTCOMERCIAL_PRA(PROV.CODPROD)
       + NVL(FUT.QTDFUTURA, 0)
       - NVL(ATV.QTDATIVA, 0)
       - PROV.QTDPROVISIONADA AS COBERTURA_APOS_FILAS
  FROM PROVISIONADA PROV
  LEFT JOIN FUTURO FUT
    ON FUT.CODPROD = PROV.CODPROD
  LEFT JOIN ATIVA ATV
    ON ATV.CODPROD = PROV.CODPROD
 ORDER BY PROV.CODPROD;
