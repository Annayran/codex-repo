/*
  MATRIZ DE REGRESSAO DAS TOPS MARCADAS PARA FILA
  Somente leitura. Considera a versao mais recente de cada TOP.
*/

WITH TOP_ATUAL AS (
    SELECT TOP.*,
           ROW_NUMBER() OVER (
               PARTITION BY TOP.CODTIPOPER
               ORDER BY TOP.DHALTER DESC
           ) AS RN
      FROM TGFTOP TOP
)
SELECT COUNT(*) AS TOPS_MARCADAS,
       SUM(CASE WHEN TIPMOV IN ('P', 'J') THEN 1 ELSE 0 END) AS DEVEM_CRIAR_FILA,
       SUM(CASE WHEN TIPMOV = 'C' THEN 1 ELSE 0 END) AS COMPRAS_CANDIDATAS_ESTOQUE_FUTURO,
       SUM(CASE WHEN TIPMOV NOT IN ('P', 'J', 'C') THEN 1 ELSE 0 END) AS NAO_DEVEM_CRIAR_FILA
  FROM TOP_ATUAL
 WHERE RN = 1
   AND NVL(AD_FILARESERVA, 'N') = 'S';

WITH TOP_ATUAL AS (
    SELECT TOP.*,
           ROW_NUMBER() OVER (
               PARTITION BY TOP.CODTIPOPER
               ORDER BY TOP.DHALTER DESC
           ) AS RN
      FROM TGFTOP TOP
)
SELECT CODTIPOPER,
       DHALTER,
       DESCROPER,
       TIPMOV,
       AD_FILARESERVA,
       CASE
           WHEN TIPMOV IN ('P', 'J') THEN 'CRIAR_FILA'
           WHEN TIPMOV = 'C' THEN 'ESTOQUE_FUTURO_SE_CONFIRMADA_E_PENDENTE'
           ELSE 'NAO_CRIAR_FILA'
       END AS RESULTADO_ESPERADO,
       CASE
           WHEN TIPMOV IN ('P', 'J')
           THEN 'TESTAR_INCLUSAO_ALTERACAO_REDUCAO_FATURAMENTO_ESTORNO_EXCLUSAO'
           WHEN TIPMOV = 'C'
           THEN 'TESTAR_SOMA_E_BAIXA_DO_SALDO_FUTURO'
           ELSE 'TESTAR_QUE_NAO_INSERE_AD_TGFSEQENT'
       END AS CENARIO_MINIMO
  FROM TOP_ATUAL
 WHERE RN = 1
   AND NVL(AD_FILARESERVA, 'N') = 'S'
 ORDER BY TIPMOV, CODTIPOPER;

-- Apos cada execucao funcional, conferir se a TOP testada deixou registros
-- indevidos fora do criterio P/J.
SELECT CAB.CODTIPOPER,
       CAB.TIPMOV,
       COUNT(*) AS REGISTROS_INDEVIDOS
  FROM AD_TGFSEQENT ENT
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ENT.NUNOTA
 WHERE CAB.TIPMOV NOT IN ('P', 'J')
 GROUP BY CAB.CODTIPOPER, CAB.TIPMOV
 ORDER BY CAB.TIPMOV, CAB.CODTIPOPER;
