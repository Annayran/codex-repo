-- Recompila a visao agregadora apos as duas visoes de fila.
-- O contrato de SALDOEST permanece como estoque comercial fisico.
CREATE OR REPLACE FORCE EDITIONABLE VIEW AD_VGFFRPROD
(CODPROD, QTDPED, SALDOEST) AS
SELECT P.CODPROD,
       COUNT(1) AS QTDPED,
       FNC_ESTCOMERCIAL_PRA(P.CODPROD) AS SALDOEST
  FROM AD_VGFRESEST P
 GROUP BY P.CODPROD
UNION
SELECT P.CODPROD,
       COUNT(1) AS QTDPED,
       FNC_ESTCOMERCIAL_PRA(P.CODPROD) AS SALDOEST
  FROM AD_VGFPROVEST P
 GROUP BY P.CODPROD;

SHOW ERRORS VIEW AD_VGFFRPROD;
