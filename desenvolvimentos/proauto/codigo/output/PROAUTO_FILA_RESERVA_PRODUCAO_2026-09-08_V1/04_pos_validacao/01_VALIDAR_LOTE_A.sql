SELECT OWNER,
       OBJECT_NAME,
       OBJECT_TYPE,
       STATUS,
       LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
   AND OBJECT_NAME = 'TRG_IUD_TGFITE_FILRES_PRA';

SELECT OWNER,
       NAME,
       TYPE,
       LINE,
       POSITION,
       TEXT
  FROM ALL_ERRORS
 WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
   AND NAME = 'TRG_IUD_TGFITE_FILRES_PRA'
 ORDER BY SEQUENCE;

