-- SOMENTE LEITURA.
-- Resultado diferente de OK mantém o Lote B bloqueado.

SELECT CASE
           WHEN COUNT(*) = 2
            AND COUNT(DISTINCT CHAVE) = 2
            AND MAX(CASE WHEN CHAVE = 'DTNOTINT' THEN INTEIRO END) >= 0
            AND REGEXP_LIKE(
                    REPLACE(REPLACE(TRIM(MAX(CASE WHEN CHAVE = 'GRPCOMINT' THEN TEXTO END)), ' ', ''), ';', ','),
                    '^[0-9]+(,[0-9]+)*$'
                )
           THEN 'OK'
           ELSE 'PARAR: revisar DTNOTINT/GRPCOMINT'
       END AS RESULTADO_LOTE_B
  FROM TSIPAR
 WHERE CHAVE IN ('DTNOTINT', 'GRPCOMINT');

SELECT CHAVE,
       INTEIRO,
       TEXTO
  FROM TSIPAR
 WHERE CHAVE IN ('DTNOTINT', 'GRPCOMINT')
 ORDER BY CHAVE;

SELECT OWNER,
       TABLE_NAME,
       COLUMN_NAME,
       DATA_TYPE,
       DATA_LENGTH,
       NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE (TABLE_NAME = 'TSIAVI' AND COLUMN_NAME IN (
        'NUAVISO', 'TITULO', 'DESCRICAO', 'SOLUCAO', 'IDENTIFICADOR',
        'IMPORTANCIA', 'CODUSU', 'CODGRUPO', 'TIPO', 'DHCRIACAO',
        'CODUSUREMETENTE', 'NUAVISOPAI'
    ))
    OR (TABLE_NAME = 'TGFNUM' AND COLUMN_NAME IN ('ARQUIVO', 'ULTCOD'))
    OR (TABLE_NAME = 'TSIUSU' AND COLUMN_NAME = 'CODGRUPO')
 ORDER BY TABLE_NAME, OWNER, COLUMN_ID;

