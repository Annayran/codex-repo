BEGIN

IF STP_GET_ATUALIZANDO OR STP_GET_FILA THEN
RETURN;
END IF;

--DELETANDO
IF DELETING THEN
DELETE FROM AD_TGFSEQENT
WHERE NUNOTA = :OLD.NUNOTA
AND SEQUENCIA = :OLD.SEQUENCIA;

RETURN;
END IF;

--CARREGA VARIAVEIS DO CABECALHO
SELECT CAB.CODTIPOPER
,CAB.DHTIPOPER
INTO V_CODTIPOPER
,V_DHTIPOPER
FROM TGFCAB CAB
WHERE CAB.NUNOTA = :NEW.NUNOTA;


--VALIDA SE FAZ PARTE DO PROCESSO DE FILA
SELECT NVL(TP.AD_FILARESERVA,'N')
INTO V_FILARESERVA
FROM TGFTOP TP
WHERE TP.CODTIPOPER = V_CODTIPOPER
AND TP.DHALTER = V_DHTIPOPER;

IF V_FILARESERVA <> 'S' THEN
RETURN;
END IF;

V_PROVISAO := 'N';
--- BUSCA INFORMACAO DE OP
BEGIN
SELECT OP.AD_DTSEPARACAO
INTO V_DTINICIO
FROM TGFCAB CAB
JOIN TPRIPROC OP ON CAB.IDIPROC = OP.IDIPROC
WHERE CAB.NUNOTA = :NEW.NUNOTA;
EXCEPTION
WHEN NO_DATA_FOUND THEN
V_PROVISAO := 'N';
END;

--VALIDA DATA DA PRODUCAO
IF V_DTINICIO IS NOT NULL THEN

:NEW.DTINICIO := V_DTINICIO;

UPDATE TGFCAB
SET DTPREVENT = V_DTINICIO
WHERE NUNOTA = :NEW.NUNOTA;

END IF;

--VERIFICA O FATURAMENTO
IF UPDATING AND NVL(:NEW.QTDENTREGUE,0) > NVL(:OLD.QTDENTREGUE,0) THEN
STP_VALIDAFAT_FILARES_PRA(:NEW.NUNOTA,:NEW.SEQUENCIA,NVL(:NEW.QTDENTREGUE,0) - NVL(:OLD.QTDENTREGUE,0), 'INSERT') ;
END IF;

--VALIDA AUMENTO DE QTD
IF :NEW.QTDNEG > :OLD.QTDNEG THEN
STP_MSGERRO('Não é possivel aumentar a quantidade!'
,'Pedido/sequencia faz parte da fila de reserva de estoque'
,'Insira uma nova linha');
END IF;

--VALIDA A EXCLUSÃO DO FATURAMENTO
IF UPDATING AND NVL(:NEW.QTDENTREGUE,0) < NVL(:OLD.QTDENTREGUE,0) THEN
STP_VALIDAFAT_FILARES_PRA(:NEW.NUNOTA,:NEW.SEQUENCIA,NVL(:NEW.QTDENTREGUE,0) - NVL(:OLD.QTDENTREGUE,0), 'DELETE') ;
ELSE

--BUSCA O PRAZO DE PROVISAO CONFORME A ORIGEM DO PRODUTO
SELECT NVL(P.INTEIRO,120)
INTO V_DIAS_PROVISAO
FROM TSIPAR P
WHERE P.CHAVE = (
    SELECT CASE
             WHEN NVL(PRO.ORIGPROD,0) IN (1,2,6,7) THEN 'DTINTERINT'
             ELSE 'DTNACINT'
           END
    FROM TGFPRO PRO
    WHERE PRO.CODPROD = :NEW.CODPROD
);

IF :NEW.DTINICIO IS NOT NULL
AND :NEW.DTINICIO - TRUNC(SYSDATE) > NVL(V_DIAS_PROVISAO,120) THEN
V_PROVISAO := 'S';
END IF;

STP_GRAVAFILA_PRA (
p_NUNOTA    => :NEW.NUNOTA,
p_SEQUENCIA => :NEW.SEQUENCIA,
p_QTDNEG    => :NEW.QTDNEG,
p_DTINICIO  => :NEW.DTINICIO,
p_CODPROD   => :NEW.CODPROD,
p_PROVISAO  => V_PROVISAO
);

