-- Read-only pre-deploy inventory. Execute in TESTE and export all result sets.

SELECT USER AS usuario_conectado,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS schema_atual
  FROM DUAL;

SELECT BANNER_FULL
  FROM V$VERSION;

SELECT OWNER, OBJECT_TYPE, OBJECT_NAME, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER = 'TESTE'
   AND OBJECT_NAME IN (
       'AD_TGFSEQENT', 'AD_VGFRESEST',
       'FNC_ESTCOMERCIAL_PRA', 'FNC_GETPOSFILARES_PRA',
       'FNC_GETSTATUSLIB_PRA', 'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_GRAVAFILA_PRA', 'STP_SETSEQPREVEST_PRA',
       'STP_VALIDAFAT_FILARES_PRA', 'TRG_IUD_TGFITE_FILRES_PRA',
       'TRG_IU_AD_TGFSEQENT_PRA'
   )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT OWNER, NAME, TYPE, LINE, POSITION, TEXT
  FROM ALL_ERRORS
 WHERE OWNER = 'TESTE'
   AND NAME IN (
       'AD_VGFRESEST', 'FNC_GETPOSFILARES_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA', 'STP_GRAVAFILA_PRA',
       'STP_SETSEQPREVEST_PRA', 'STP_VALIDAFAT_FILARES_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA', 'TRG_IU_AD_TGFSEQENT_PRA'
   )
 ORDER BY NAME, SEQUENCE;

SELECT COUNT(*) AS total_fila_ativa,
       SUM(CASE WHEN DTPREVENT = DATE '2999-12-12' THEN 1 ELSE 0 END) AS sem_previsao_real
  FROM TESTE.AD_VGFRESEST;

SELECT COUNT(*) AS grupos_repetidos,
       NVL(SUM(qtd), 0) AS linhas_nos_grupos,
       NVL(SUM(qtd) - COUNT(*), 0) AS linhas_excedentes,
       NVL(MAX(qtd), 0) AS maior_repeticao
  FROM (
        SELECT CODPROD, AD_SEQRESERVA, COUNT(*) AS qtd
          FROM TESTE.AD_VGFRESEST
         GROUP BY CODPROD, AD_SEQRESERVA
        HAVING COUNT(*) > 1
       );

SELECT COUNT(*) AS grupos_nota_item_fracionados,
       NVL(SUM(qtd), 0) AS linhas_nos_grupos
  FROM (
        SELECT NUNOTA, SEQUENCIA, COUNT(*) AS qtd
          FROM TESTE.AD_TGFSEQENT
         GROUP BY NUNOTA, SEQUENCIA
        HAVING COUNT(*) > 1
       );

