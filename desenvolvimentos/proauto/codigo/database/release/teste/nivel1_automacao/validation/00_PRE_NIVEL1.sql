SELECT USER AS USUARIO,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS SCHEMA_ATUAL,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS BANCO
  FROM DUAL;

SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'PRA_PKG_FILARES',
       'STP_GRAVAFILA_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_ATUALIZA_PROV_FILA_BTN',
       'STP_SETSEQPREVEST_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NVL(PROVISAO, '<NULL>') AS PROVISAO,
       COUNT(*) AS QUANTIDADE
  FROM AD_TGFSEQENT
 GROUP BY NVL(PROVISAO, '<NULL>')
 ORDER BY PROVISAO;

SELECT COUNT(*) AS QUANTIDADES_INVALIDAS
  FROM AD_TGFSEQENT
 WHERE QTDENT IS NULL
    OR QTDENT < 0
    OR NVL(QTDENTREGUE, 0) < 0
    OR NVL(QTDENTREGUE, 0) > NVL(QTDENT, 0);
