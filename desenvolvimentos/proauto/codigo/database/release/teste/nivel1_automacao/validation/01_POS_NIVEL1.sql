SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'PRA_PKG_FILARES',
       'STP_GRAVAFILA_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_ATUALIZA_PROV_FILA_BTN',
       'STP_SETSEQPREVEST_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NAME, TYPE, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME IN (
       'PRA_PKG_FILARES',
       'STP_GRAVAFILA_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_ATUALIZA_PROV_FILA_BTN',
       'STP_SETSEQPREVEST_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA'
 )
 ORDER BY NAME, SEQUENCE;

SELECT PRA_PKG_FILARES.OBTER_DIAS_JANELA AS DIAS_UTEIS
  FROM DUAL;

SELECT PRA_PKG_FILARES.CALCULAR_PROVISAO(
           TRUNC(SYSDATE) + 1,
           1,
           TRUNC(SYSDATE)
       ) AS PROVISAO_DATA_PROXIMA
  FROM DUAL;
