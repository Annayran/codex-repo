SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'STP_VALIDAFAT_FILARES_PRA',
       'AD_VGFRESEST',
       'AD_VGFPROVEST',
       'AD_VGFFRPROD'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NAME, TYPE, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME IN (
       'STP_VALIDAFAT_FILARES_PRA',
       'AD_VGFRESEST',
       'AD_VGFPROVEST',
       'AD_VGFFRPROD'
 )
 ORDER BY NAME, SEQUENCE;

SELECT COUNT(*) AS FILA_ATIVA
  FROM AD_VGFRESEST;

SELECT COUNT(*) AS FILA_PROVISIONADA
  FROM AD_VGFPROVEST;

SELECT COUNT(*) AS COMPRAS_FUTURAS_PENDENTES,
       NVL(SUM(GREATEST(NVL(ITE.QTDNEG, 0) - NVL(ITE.QTDENTREGUE, 0), 0)), 0)
           AS QUANTIDADE_FUTURA
  FROM TGFITE ITE
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
 WHERE CAB.TIPMOV = 'C'
   AND CAB.STATUSNOTA = 'L'
   AND ITE.PENDENTE = 'S';

