SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'STP_VALIDAFAT_FILARES_PRA',
       'AD_VGFRESEST',
       'AD_VGFPROVEST',
       'AD_VGFFRPROD'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT COUNT(*) AS FILA_ATIVA
  FROM AD_VGFRESEST;

SELECT COUNT(*) AS FILA_PROVISIONADA
  FROM AD_VGFPROVEST;

SELECT COUNT(*) AS POSICOES_REPETIDAS
  FROM (
        SELECT CODPROD, AD_SEQRESERVA
          FROM AD_VGFRESEST
         GROUP BY CODPROD, AD_SEQRESERVA
        HAVING COUNT(*) > 1
  );

