CREATE OR REPLACE FORCE EDITIONABLE VIEW AD_VGFRESEST
(
    AD_SEQRESERVA, STATUSNOTA, ORDEM, NUNOTA, SEQUENCIA,
    QTDORIGINAL, IDIPROC, SEQPREV, REFERENCIA, CODPROD,
    DTNEG, DHMOV, CODUSUINC, CODUSU, CODVEND, CODPARC,
    CODTIPOPER, DESCROPER, DTPREVENT, CODLOCALORIG,
    QTDPENDENTE, SALDO
) AS
SELECT ENT.SEQENT AS AD_SEQRESERVA,
       FNC_GETSTATUSLIB_PRA(CAB.NUNOTA) AS STATUSNOTA,
       DENSE_RANK() OVER (
           PARTITION BY ITE.CODPROD
           ORDER BY ENT.SEQENT
       ) AS ORDEM,
       ITE.NUNOTA,
       ITE.SEQUENCIA,
       ITE.QTDNEG AS QTDORIGINAL,
       CAB.IDIPROC,
       ENT.SEQENT AS SEQPREV,
       PRO.REFERENCIA,
       ITE.CODPROD,
       CAB.DTNEG,
       ENT.DTLANC AS DHMOV,
       CAB.CODUSU AS CODUSUINC,
       ITE.CODUSU,
       CAB.CODVEND,
       CAB.CODPARC,
       CAB.CODTIPOPER,
       TOP.DESCROPER,
       NVL(ENT.DTPREV, NVL(CAB.DTPREVENT, DATE '2999-12-12')) AS DTPREVENT,
       ITE.CODLOCALORIG,
       ENT.QTDENT - NVL(ENT.QTDENTREGUE, 0) AS QTDPENDENTE,
       FNC_ESTCOMERCIAL_PRA(ITE.CODPROD)
       + NVL(FUT.QTDFUTURA, 0)
       - SUM(ENT.QTDENT - NVL(ENT.QTDENTREGUE, 0)) OVER (
             PARTITION BY ITE.CODPROD
             ORDER BY ENT.SEQENT
             RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
         ) AS SALDO
  FROM TGFITE ITE
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
  JOIN AD_TGFSEQENT ENT
    ON ENT.NUNOTA = ITE.NUNOTA
   AND ENT.SEQUENCIA = ITE.SEQUENCIA
  JOIN TGFPRO PRO
    ON PRO.CODPROD = ITE.CODPROD
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN (
      SELECT ITEC.CODPROD,
             SUM(
                 GREATEST(
                     NVL(ITEC.QTDNEG, 0) - NVL(ITEC.QTDENTREGUE, 0),
                     0
                 )
             ) AS QTDFUTURA
        FROM TGFITE ITEC
        JOIN TGFCAB CABC
          ON CABC.NUNOTA = ITEC.NUNOTA
       WHERE CABC.TIPMOV = 'C'
         AND CABC.STATUSNOTA = 'L'
         AND ITEC.PENDENTE = 'S'
       GROUP BY ITEC.CODPROD
  ) FUT
    ON FUT.CODPROD = ITE.CODPROD
 WHERE ITE.PENDENTE = 'S'
   AND CAB.TIPMOV IN ('P', 'J')
   AND CAB.STATUSNOTA = 'L'
   AND NVL(TOP.AD_FILARESERVA, 'N') = 'S'
   AND ENT.SEQENT IS NOT NULL
   AND ENT.QTDENT - NVL(ENT.QTDENTREGUE, 0) > 0
   AND NVL(ENT.PROVISAO, 'N') = 'N'
 ORDER BY ITE.CODPROD,
          ENT.SEQENT,
          ITE.NUNOTA,
          ITE.SEQUENCIA;

SHOW ERRORS VIEW AD_VGFRESEST;
