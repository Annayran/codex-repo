  O documento ZY-PROA-2026-VALFIL-001, Q13, confirma que o saneamento dos
  registros sem previsao foi realizado na Fase 1. Este arquivo nao executa DML.
*/

SELECT COUNT(*) AS ATIVOS_SEM_DTPREV,
       SUM(
           CASE
               WHEN NVL(OP.AD_DTSEPARACAO, NVL(ITE.DTINICIO, CAB.DTPREVENT)) IS NOT NULL
               THEN 1
               ELSE 0
           END
       ) AS COM_DATA_FONTE_DISPONIVEL
  FROM AD_TGFSEQENT ENT
  JOIN TGFITE ITE
    ON ITE.NUNOTA = ENT.NUNOTA
   AND ITE.SEQUENCIA = ENT.SEQUENCIA
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN TPRIPROC OP
    ON OP.IDIPROC = CAB.IDIPROC
 WHERE ENT.DTPREV IS NULL
   AND ITE.PENDENTE = 'S'
   AND CAB.STATUSNOTA = 'L'
   AND CAB.TIPMOV IN ('P', 'J')
   AND NVL(TOP.AD_FILARESERVA, 'N') = 'S';

SELECT ENT.NUNOTA,
       ENT.SEQUENCIA,
       ENT.SEQENT,
       ENT.CODPROD,
       ENT.PROVISAO,
       NVL(OP.AD_DTSEPARACAO, NVL(ITE.DTINICIO, CAB.DTPREVENT)) AS DATA_FONTE
  FROM AD_TGFSEQENT ENT
  JOIN TGFITE ITE
    ON ITE.NUNOTA = ENT.NUNOTA
   AND ITE.SEQUENCIA = ENT.SEQUENCIA
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN TPRIPROC OP
    ON OP.IDIPROC = CAB.IDIPROC
 WHERE ENT.DTPREV IS NULL
   AND ITE.PENDENTE = 'S'
   AND CAB.STATUSNOTA = 'L'
   AND CAB.TIPMOV IN ('P', 'J')
   AND NVL(TOP.AD_FILARESERVA, 'N') = 'S'
 ORDER BY ENT.CODPROD, ENT.SEQENT;
