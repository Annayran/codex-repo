-- 01. Total real sem o limite de 5.000 linhas da exportacao detalhada.
SELECT COUNT(*) AS TOTAL_SEM_DTPREV,
       SUM(CASE WHEN NVL(OP.AD_DTSEPARACAO, NVL(ITE.DTINICIO, CAB.DTPREVENT)) IS NOT NULL
                THEN 1 ELSE 0 END) AS COM_FONTE_CANDIDATA,
       SUM(CASE WHEN ENT.PROVISAO IS NULL THEN 1 ELSE 0 END) AS PROVISAO_NULA,
       SUM(CASE WHEN NVL(ENT.PROVISAO, 'N') = 'N' THEN 1 ELSE 0 END) AS ATIVOS,
       SUM(CASE WHEN ENT.PROVISAO = 'S' THEN 1 ELSE 0 END) AS PROVISIONADOS
  FROM AD_TGFSEQENT ENT
  JOIN TGFITE ITE
    ON ITE.NUNOTA = ENT.NUNOTA
   AND ITE.SEQUENCIA = ENT.SEQUENCIA
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN TPRIPROC OP
    ON OP.IDIPROC = CAB.IDIPROC
 WHERE ENT.DTPREV IS NULL
   AND ITE.PENDENTE = 'S'
   AND CAB.STATUSNOTA = 'L'
   AND CAB.TIPMOV IN ('P', 'J')
   AND NVL(TOP.AD_FILARESERVA, 'N') = 'S';

-- 02. Fragmentos com decisao manual mista N/S; devem ser preservados.
SELECT COUNT(*) AS ITENS_COM_PROVISAO_MISTA
  FROM (
        SELECT NUNOTA, SEQUENCIA, CODPROD
          FROM AD_TGFSEQENT
         GROUP BY NUNOTA, SEQUENCIA, CODPROD
        HAVING COUNT(*) > 1
           AND MIN(NVL(PROVISAO, 'N')) = 'N'
           AND MAX(NVL(PROVISAO, 'N')) = 'S'
       );

-- 03. Posicoes compartilhadas; a view candidata usa RANGE para saldo comum.
SELECT COUNT(*) AS GRUPOS_COM_POSICAO_COMPARTILHADA,
       NVL(SUM(QUANTIDADE), 0) AS LINHAS_ENVOLVIDAS
  FROM (
        SELECT CODPROD, AD_SEQRESERVA, COUNT(*) AS QUANTIDADE
          FROM AD_VGFRESEST
         GROUP BY CODPROD, AD_SEQRESERVA
        HAVING COUNT(*) > 1
       );

-- 04. Versao atual das TOPs de OE. A evidencia recebida apontou 23, todas N.
WITH TOP_ATUAL AS (
    SELECT TOP.CODTIPOPER,
           TOP.DHALTER,
           TOP.DESCROPER,
           TOP.TIPMOV,
           NVL(TOP.AD_FILARESERVA, 'N') AS AD_FILARESERVA,
           ROW_NUMBER() OVER (
               PARTITION BY TOP.CODTIPOPER
               ORDER BY TOP.DHALTER DESC
           ) AS RN
      FROM TGFTOP TOP
     WHERE UPPER(TOP.DESCROPER) LIKE '%ORDEM%EXPEDI%'
        OR UPPER(TOP.DESCROPER) LIKE 'OE%'
)
SELECT CODTIPOPER,
       DHALTER,
       DESCROPER,
       TIPMOV,
       AD_FILARESERVA
  FROM TOP_ATUAL
 WHERE RN = 1
 ORDER BY CODTIPOPER;

-- 05. Limites atuais para validar a folga tecnica de SEQENT.
SELECT MIN(SEQENT) AS MENOR_SEQENT,
       MAX(SEQENT) AS MAIOR_SEQENT,
       COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CODPROD) AS PRODUTOS
  FROM AD_TGFSEQENT;
