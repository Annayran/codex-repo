SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'PRA_PKG_FILARES',
       'STP_GRAVAFILA_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_ATUALIZA_PROV_FILA_BTN',
       'STP_VALIDAFAT_FILARES_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA',
       'AD_VGFRESEST',
       'AD_VGFPROVEST',
       'AD_VGFFRPROD'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NAME, TYPE, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME IN (
       'PRA_PKG_FILARES',
       'STP_GRAVAFILA_PRA',
       'STP_ATUALIZA_PROV_FILA_PRA',
       'STP_ATUALIZA_PROV_FILA_BTN',
       'STP_VALIDAFAT_FILARES_PRA',
       'TRG_IUD_TGFITE_FILRES_PRA',
       'AD_VGFRESEST',
       'AD_VGFPROVEST',
       'AD_VGFFRPROD'
 )
 ORDER BY NAME, SEQUENCE;

SELECT COUNT(*) AS POSICOES_REPETIDAS
  FROM (
        SELECT CODPROD, AD_SEQRESERVA
          FROM AD_VGFRESEST
         GROUP BY CODPROD, AD_SEQRESERVA
        HAVING COUNT(*) > 1
       );

SELECT COUNT(*) AS PROVISOES_ATIVAVEIS
  FROM AD_TGFSEQENT ENT
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ENT.NUNOTA
 WHERE NVL(ENT.PROVISAO, 'N') = 'S'
   AND ENT.DTPREV IS NOT NULL
   AND PRA_PKG_FILARES.CALCULAR_PROVISAO(ENT.DTPREV, CAB.CODEMP) = 'N';

SELECT PRA_PKG_FILARES.OBTER_DIAS_JANELA AS JANELA_DIAS_UTEIS
  FROM DUAL;
