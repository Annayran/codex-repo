SELECT OBJECT_TYPE, OBJECT_NAME, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'PRA_PKG_FILARES',
       'STP_ATUALIZA_PROV_FILA_PRA'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT COUNT(*) AS PROVISIONADOS_SEM_DATA
  FROM AD_TGFSEQENT
 WHERE NVL(PROVISAO, 'N') = 'S'
   AND DTPREV IS NULL;

SELECT COUNT(*) AS QUANTIDADES_INVALIDAS
  FROM AD_TGFSEQENT
 WHERE QTDENT IS NULL
    OR QTDENT < 0
    OR NVL(QTDENTREGUE, 0) < 0
    OR NVL(QTDENTREGUE, 0) > NVL(QTDENT, 0);

SELECT NUNOTA, SEQUENCIA, CODPROD, COUNT(*) AS FRAGMENTOS,
       SUM(QTDENT) AS QTD_FILA
  FROM AD_TGFSEQENT
 GROUP BY NUNOTA, SEQUENCIA, CODPROD
HAVING COUNT(*) > 1
 ORDER BY FRAGMENTOS DESC;
