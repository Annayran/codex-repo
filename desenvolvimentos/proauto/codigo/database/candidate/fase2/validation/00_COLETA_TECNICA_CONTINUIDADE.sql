-- BLOCO 01_AMBIENTE
SELECT USER AS USUARIO,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS SCHEMA_ATUAL,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS BANCO
  FROM DUAL;

-- BLOCO 02_TSIFER_ESTRUTURA
SELECT OWNER,
       TABLE_NAME,
       COLUMN_ID,
       COLUMN_NAME,
       DATA_TYPE,
       NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE TABLE_NAME IN ('TSIFER', 'TSIEMP', 'TSICID', 'TSIUFS')
 ORDER BY TABLE_NAME, COLUMN_ID;

-- BLOCO 03_TSIFER_DOMINIOS
SELECT NVL(NACIONAL, '<NULL>') AS NACIONAL,
       NVL(OBRIGATORIO, '<NULL>') AS OBRIGATORIO,
       NVL(RECORRENTE, '<NULL>') AS RECORRENTE,
       COUNT(*) AS QUANTIDADE,
       MIN(DTFERIADO) AS PRIMEIRA_DATA,
       MAX(DTFERIADO) AS ULTIMA_DATA
  FROM TSIFER
 GROUP BY NVL(NACIONAL, '<NULL>'),
          NVL(OBRIGATORIO, '<NULL>'),
          NVL(RECORRENTE, '<NULL>')
 ORDER BY 1, 2, 3;

-- BLOCO 04_EMPRESAS_CALENDARIO
SELECT EMP.CODEMP,
       EMP.CODCID,
       CID.NOMECID,
       CID.UF AS CODUF,
       UFS.UF,
       UFS.CODPAIS
  FROM TSIEMP EMP
  JOIN TSICID CID
    ON CID.CODCID = EMP.CODCID
  JOIN TSIUFS UFS
    ON UFS.CODUF = CID.UF
 ORDER BY EMP.CODEMP;

-- BLOCO 05_DDL_VIEWS (exportar sem truncar a coluna DDL)
SELECT OBJECT_NAME,
       DBMS_METADATA.GET_DDL('VIEW', OBJECT_NAME, OWNER) AS DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'TESTE'
   AND OBJECT_TYPE = 'VIEW'
   AND OBJECT_NAME IN ('AD_VGFPROVEST', 'AD_VGFFRPROD', 'AD_VGFRESEST')
 ORDER BY OBJECT_NAME;

-- BLOCO 06_COMPRAS_FUTURAS_POR_TOP
SELECT CAB.CODTIPOPER,
       TOP.DESCROPER,
       CAB.TIPMOV,
       COUNT(DISTINCT CAB.NUNOTA) AS PEDIDOS,
       COUNT(*) AS ITENS,
       SUM(GREATEST(NVL(ITE.QTDNEG, 0) - NVL(ITE.QTDENTREGUE, 0), 0)) AS QTDPENDENTE
  FROM TGFCAB CAB
  JOIN TGFITE ITE
    ON ITE.NUNOTA = CAB.NUNOTA
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
 WHERE CAB.TIPMOV = 'C'
   AND CAB.STATUSNOTA = 'L'
   AND ITE.PENDENTE = 'S'
 GROUP BY CAB.CODTIPOPER, TOP.DESCROPER, CAB.TIPMOV
 ORDER BY CAB.CODTIPOPER;

-- BLOCO 07_TOPS_CANDIDATAS_OE
SELECT TOP.CODTIPOPER,
       TOP.DHALTER,
       TOP.DESCROPER,
       TOP.TIPMOV,
       NVL(TOP.AD_FILARESERVA, 'N') AS AD_FILARESERVA
  FROM TGFTOP TOP
 WHERE UPPER(TOP.DESCROPER) LIKE '%EXPEDI%'
    OR UPPER(TOP.DESCROPER) LIKE '%ORDEM%ENTREGA%'
    OR UPPER(TOP.DESCROPER) LIKE '%ORDEM%EXPED%'
 ORDER BY TOP.CODTIPOPER, TOP.DHALTER DESC;

-- BLOCO 08_LIMITES_SEQENT
SELECT MIN(SEQENT) AS MENOR_SEQENT,
       MAX(SEQENT) AS MAIOR_SEQENT,
       COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CODPROD) AS PRODUTOS
  FROM AD_TGFSEQENT;

-- BLOCO 09_POSICOES_REPETIDAS_ATIVAS
SELECT CODPROD,
       AD_SEQRESERVA,
       COUNT(*) AS QUANTIDADE
  FROM AD_VGFRESEST
 GROUP BY CODPROD, AD_SEQRESERVA
HAVING COUNT(*) > 1
 ORDER BY CODPROD, AD_SEQRESERVA;

-- BLOCO 10_FRAGMENTOS_PROVISIONADOS
SELECT NUNOTA,
       SEQUENCIA,
       CODPROD,
       COUNT(*) AS FRAGMENTOS,
       SUM(QTDENT) AS QTD_TOTAL,
       MIN(DTPREV) AS DTPREV,
       MIN(NVL(PROVISAO, 'N')) AS MENOR_PROVISAO,
       MAX(NVL(PROVISAO, 'N')) AS MAIOR_PROVISAO
  FROM AD_TGFSEQENT
 GROUP BY NUNOTA, SEQUENCIA, CODPROD
HAVING COUNT(*) > 1
   AND MAX(NVL(PROVISAO, 'N')) = 'S'
 ORDER BY CODPROD, NUNOTA, SEQUENCIA;

-- BLOCO 11_SEM_PREVISAO_E_FONTE_CANDIDATA
SELECT ENT.NUNOTA,
       ENT.SEQUENCIA,
       ENT.SEQENT,
       ENT.CODPROD,
       ENT.PROVISAO,
       ENT.DTPREV,
       OP.AD_DTSEPARACAO,
       ITE.DTINICIO,
       CAB.DTPREVENT,
       NVL(OP.AD_DTSEPARACAO, NVL(ITE.DTINICIO, CAB.DTPREVENT)) AS DTPREV_CANDIDATA
  FROM AD_TGFSEQENT ENT
  JOIN TGFITE ITE
    ON ITE.NUNOTA = ENT.NUNOTA
   AND ITE.SEQUENCIA = ENT.SEQUENCIA
  JOIN TGFCAB CAB
    ON CAB.NUNOTA = ITE.NUNOTA
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN TPRIPROC OP
    ON OP.IDIPROC = CAB.IDIPROC
 WHERE ENT.DTPREV IS NULL
   AND ITE.PENDENTE = 'S'
   AND CAB.STATUSNOTA = 'L'
   AND CAB.TIPMOV IN ('P', 'J')
   AND NVL(TOP.AD_FILARESERVA, 'N') = 'S'
 ORDER BY ENT.CODPROD, ENT.SEQENT, ENT.NUNOTA, ENT.SEQUENCIA;

-- BLOCO 12_DEPENDENCIAS_DAS_VIEWS
SELECT OWNER,
       NAME,
       TYPE,
       REFERENCED_OWNER,
       REFERENCED_NAME,
       REFERENCED_TYPE
  FROM ALL_DEPENDENCIES
 WHERE OWNER = 'TESTE'
   AND NAME IN ('AD_VGFPROVEST', 'AD_VGFFRPROD', 'AD_VGFRESEST')
 ORDER BY NAME, REFERENCED_TYPE, REFERENCED_NAME;
