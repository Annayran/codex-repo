-- 1. Confirmar objeto e colunas na versão 4.36b124.
SELECT OWNER,
       OBJECT_TYPE,
       OBJECT_NAME,
       STATUS
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME = 'TSIFER'
 ORDER BY OWNER, OBJECT_TYPE;

SELECT OWNER,
       TABLE_NAME,
       COLUMN_ID,
       COLUMN_NAME,
       DATA_TYPE,
       NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE TABLE_NAME = 'TSIFER'
 ORDER BY OWNER, COLUMN_ID;

-- 2. Levantar os domínios realmente cadastrados, sem presumir códigos.
SELECT NVL(NACIONAL, '<NULL>') AS NACIONAL,
       NVL(OBRIGATORIO, '<NULL>') AS OBRIGATORIO,
       NVL(RECORRENTE, '<NULL>') AS RECORRENTE,
       COUNT(*) AS QUANTIDADE
  FROM TSIFER
 GROUP BY NVL(NACIONAL, '<NULL>'),
          NVL(OBRIGATORIO, '<NULL>'),
          NVL(RECORRENTE, '<NULL>')
 ORDER BY 1, 2, 3;

-- 3. Verificar cobertura do calendário a partir do ano corrente.
SELECT EXTRACT(YEAR FROM DTFERIADO) AS ANO,
       COUNT(*) AS QUANTIDADE
  FROM TSIFER
 WHERE DTFERIADO >= TRUNC(SYSDATE, 'YYYY')
 GROUP BY EXTRACT(YEAR FROM DTFERIADO)
 ORDER BY ANO;

-- 4. Confirmar como a empresa de cada pedido chega a cidade, UF e país.
SELECT CAB.CODEMP,
       EMP.CODPARC,
       EMP.CODCID,
       CID.UF,
       UFS.CODPAIS,
       COUNT(*) AS ITENS_PROVISIONADOS
  FROM AD_TGFSEQENT ENT
  JOIN TGFCAB CAB ON CAB.NUNOTA = ENT.NUNOTA
  JOIN TSIEMP EMP ON EMP.CODEMP = CAB.CODEMP
  JOIN TSICID CID ON CID.CODCID = EMP.CODCID
  JOIN TSIUFS UFS ON UFS.CODUF = CID.UF
 WHERE NVL(ENT.PROVISAO, 'N') = 'S'
 GROUP BY CAB.CODEMP, EMP.CODPARC, EMP.CODCID, CID.UF, UFS.CODPAIS
 ORDER BY CAB.CODEMP;

-- 5. Dimensionar nulos e o efeito incorreto do critério atual.
SELECT COUNT(*) AS TOTAL_PROVISIONADO,
       SUM(CASE WHEN DTPREV IS NULL THEN 1 ELSE 0 END) AS SEM_DTPREV,
       SUM(CASE WHEN DTPREV < TRUNC(SYSDATE) THEN 1 ELSE 0 END) AS DTPREV_VENCIDA,
       SUM(CASE
               WHEN DTPREV IS NOT NULL
                AND TRUNC(DTPREV - SYSDATE) <= 120
               THEN 1 ELSE 0
           END) AS ELEGIVEIS_CRITERIO_ATUAL
  FROM AD_TGFSEQENT
 WHERE NVL(PROVISAO, 'N') = 'S';

-- 6. Verificar colisões já existentes na posição por produto.
SELECT CODPROD,
       SEQENT,
       COUNT(*) AS QUANTIDADE
  FROM AD_TGFSEQENT
 WHERE SEQENT IS NOT NULL
 GROUP BY CODPROD, SEQENT
HAVING COUNT(*) > 1
 ORDER BY CODPROD, SEQENT;
