-- Executar somente depois de publicar o pacote em homologação.

SELECT PRA_PKG_FILARES.TOP_CRIAR_RESERVA('S', 'P') AS CRIA_P,
       PRA_PKG_FILARES.TOP_CRIAR_RESERVA('S', 'J') AS CRIA_J,
       PRA_PKG_FILARES.TOP_CRIAR_RESERVA('S', 'V') AS NAO_CRIA_V,
       PRA_PKG_FILARES.TOP_CRIAR_RESERVA('N', 'P') AS NAO_CRIA_FLAG_N,
       PRA_PKG_FILARES.TOP_CRIAR_RESERVA(NULL, 'P') AS NAO_CRIA_FLAG_NULL,
       PRA_PKG_FILARES.TOP_PROTEGER_ESTOQUE('S') AS PROTEGE_S,
       PRA_PKG_FILARES.TOP_PROTEGER_ESTOQUE('N') AS NAO_PROTEGE_N
  FROM DUAL;

SELECT OWNER,
       OBJECT_TYPE,
       OBJECT_NAME,
       STATUS
  FROM ALL_OBJECTS
 WHERE OWNER = 'TESTE'
   AND OBJECT_NAME IN ('PRA_PKG_FILARES', 'TRG_IUD_TGFITE_FILRES_PRA')
 ORDER BY OBJECT_TYPE,
          OBJECT_NAME;

SELECT OWNER,
       NAME,
       TYPE,
       LINE,
       POSITION,
       TEXT
  FROM ALL_ERRORS
 WHERE OWNER = 'TESTE'
   AND NAME IN ('PRA_PKG_FILARES', 'TRG_IUD_TGFITE_FILRES_PRA')
 ORDER BY NAME,
          SEQUENCE;

