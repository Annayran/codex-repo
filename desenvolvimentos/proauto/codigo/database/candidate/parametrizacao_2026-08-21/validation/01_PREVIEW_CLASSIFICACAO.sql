-- Somente leitura: mostra qual parâmetro será aplicado por produto da fila.
SELECT ITE.NUNOTA,
       ITE.SEQUENCIA,
       ITE.CODPROD,
       PRO.ORIGPROD,
       CASE
           WHEN PRO.ORIGPROD IN (1, 2, 6, 7) THEN 'INTERNACIONAL'
           ELSE 'NACIONAL'
       END AS CLASSIFICACAO,
       CASE
           WHEN PRO.ORIGPROD IN (1, 2, 6, 7) THEN 'DTINTERINT'
           ELSE 'DTNACINT'
       END AS CHAVE_TSIPAR,
       CASE
           WHEN PRO.ORIGPROD IN (1, 2, 6, 7) THEN P_INT.INTEIRO
           ELSE P_NAC.INTEIRO
       END AS DIAS_PARAMETRO,
       CAB.DTPREVENT,
       TRUNC(CAB.DTPREVENT) - TRUNC(SYSDATE) AS DIAS_ATE_PREVISAO,
       CASE
           WHEN TRUNC(CAB.DTPREVENT) - TRUNC(SYSDATE) >
                CASE
                    WHEN PRO.ORIGPROD IN (1, 2, 6, 7) THEN P_INT.INTEIRO
                    ELSE P_NAC.INTEIRO
                END
           THEN 'S'
           ELSE 'N'
       END AS PROVISAO_CALCULADA
  FROM TGFCAB CAB
  JOIN TGFITE ITE
    ON ITE.NUNOTA = CAB.NUNOTA
  JOIN TGFPRO PRO
    ON PRO.CODPROD = ITE.CODPROD
  JOIN TGFTOP TOP
    ON TOP.CODTIPOPER = CAB.CODTIPOPER
   AND TOP.DHALTER = CAB.DHTIPOPER
  LEFT JOIN TSIPAR P_INT
    ON P_INT.CHAVE = 'DTINTERINT'
  LEFT JOIN TSIPAR P_NAC
    ON P_NAC.CHAVE = 'DTNACINT'
 WHERE NVL(TOP.AD_FILARESERVA, 'N') = 'S'
   AND CAB.STATUSNOTA = 'L'
 ORDER BY ITE.NUNOTA, ITE.SEQUENCIA;

