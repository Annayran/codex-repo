SELECT OBJECT_NAME,
       OBJECT_TYPE,
       STATUS,
       LAST_DDL_TIME
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'TRG_IUD_TGFITE_FILRES_PRA',
       'PRA_ACTION_NOTIF_COMPRA_INT'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NAME,
       TYPE,
       LINE,
       POSITION,
       TEXT
  FROM USER_ERRORS
 WHERE NAME IN (
       'TRG_IUD_TGFITE_FILRES_PRA',
       'PRA_ACTION_NOTIF_COMPRA_INT'
 )
 ORDER BY NAME, SEQUENCE;

SELECT CHAVE,
       INTEIRO,
       TEXTO
  FROM TSIPAR
 WHERE CHAVE IN ('DTNACINT', 'DTINTERINT', 'DTNOTINT', 'GRPCOMINT')
 ORDER BY CHAVE;

