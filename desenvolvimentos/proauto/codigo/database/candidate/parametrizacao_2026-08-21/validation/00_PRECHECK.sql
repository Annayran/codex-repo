-- Somente leitura. Executar no mesmo schema em que os objetos serão publicados.

SELECT USER AS USUARIO,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS SCHEMA_ATUAL,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS BANCO
  FROM DUAL;

SELECT CHAVE,
       INTEIRO,
       TEXTO
  FROM TSIPAR
 WHERE CHAVE IN ('DTNACINT', 'DTINTERINT', 'DTNOTINT', 'GRPCOMINT')
 ORDER BY CHAVE;

SELECT TABLE_NAME,
       COLUMN_NAME,
       DATA_TYPE,
       DATA_LENGTH,
       NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'TSIPAR' AND COLUMN_NAME IN ('CHAVE', 'INTEIRO', 'TEXTO'))
    OR (TABLE_NAME = 'TSIAVI' AND COLUMN_NAME IN (
        'NUAVISO', 'TITULO', 'DESCRICAO', 'IDENTIFICADOR', 'CODUSU',
        'CODGRUPO', 'TIPO', 'DHCRIACAO', 'CODUSUREMETENTE'
    ))
    OR (TABLE_NAME = 'TGFPRO' AND COLUMN_NAME = 'ORIGPROD')
 ORDER BY TABLE_NAME, COLUMN_ID;

SELECT NVL(TO_CHAR(ORIGPROD), '<NULL>') AS ORIGPROD,
       COUNT(*) AS PRODUTOS
  FROM TGFPRO
 GROUP BY ORIGPROD
 ORDER BY ORIGPROD;

SELECT OBJECT_NAME,
       OBJECT_TYPE,
       STATUS,
       LAST_DDL_TIME
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN (
       'TRG_IUD_TGFITE_FILRES_PRA',
       'STP_GRAVAFILA_PRA',
       'STP_VALIDAFAT_FILARES_PRA',
       'AD_VGFRESEST',
       'PRA_ACTION_NOTIF_COMPRA_INT'
 )
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT ARQUIVO,
       ULTCOD
  FROM TGFNUM
 WHERE ARQUIVO = 'TSIAVI';

SELECT COUNT(*) AS USUARIOS_GRUPOS_CONFIGURADOS
  FROM TSIUSU U
 WHERE U.CODGRUPO IN (
       SELECT TO_NUMBER(TRIM(REGEXP_SUBSTR(P.TEXTO, '[^,;]+', 1, LEVEL)))
         FROM TSIPAR P
        WHERE P.CHAVE = 'GRPCOMINT'
      CONNECT BY LEVEL <= REGEXP_COUNT(P.TEXTO, '[,;]') + 1
            AND PRIOR SYS_GUID() IS NOT NULL
            AND PRIOR P.CHAVE = P.CHAVE
 );

-- Conferir erros antes de continuar.
SELECT NAME,
       TYPE,
       LINE,
       POSITION,
       TEXT
  FROM USER_ERRORS
 WHERE NAME IN (
       'TRG_IUD_TGFITE_FILRES_PRA',
       'STP_GRAVAFILA_PRA',
       'STP_VALIDAFAT_FILARES_PRA',
       'AD_VGFRESEST'
 )
 ORDER BY NAME, SEQUENCE;
