WITH PARAMETROS AS (
    SELECT MAX(CASE WHEN CHAVE = 'DTNOTINT' THEN INTEIRO END) AS DIAS,
           MAX(CASE WHEN CHAVE = 'GRPCOMINT' THEN TEXTO END) AS GRUPOS
      FROM TSIPAR
     WHERE CHAVE IN ('DTNOTINT', 'GRPCOMINT')
),
GRUPOS AS (
    SELECT DISTINCT
           TO_NUMBER(TRIM(REGEXP_SUBSTR(P.GRUPOS, '[^,;]+', 1, LEVEL))) AS CODGRUPO
      FROM PARAMETROS P
    CONNECT BY LEVEL <= REGEXP_COUNT(P.GRUPOS, '[,;]') + 1
          AND PRIOR SYS_GUID() IS NOT NULL
)
SELECT DISTINCT
       CAB.NUNOTA,
       CAB.NUMNOTA,
       CAB.CODEMP,
       CAB.CODPARC,
       CAB.DTPREVENT,
       TRUNC(CAB.DTPREVENT) - TRUNC(SYSDATE) AS DIAS_RESTANTES,
       G.CODGRUPO,
       (SELECT COUNT(*) FROM TSIUSU U WHERE U.CODGRUPO = G.CODGRUPO) AS USUARIOS_GRUPO,
       'FRI:' || CAB.NUNOTA || ':' || G.CODGRUPO || ':' ||
       TO_CHAR(CAB.DTPREVENT, 'YYYYMMDD') AS IDENTIFICADOR
  FROM TGFCAB CAB
  JOIN TGFITE ITE
    ON ITE.NUNOTA = CAB.NUNOTA
  JOIN TGFPRO PRO
    ON PRO.CODPROD = ITE.CODPROD
 CROSS JOIN PARAMETROS P
 CROSS JOIN GRUPOS G
 WHERE CAB.TIPMOV = 'C'
   AND CAB.STATUSNOTA = 'L'
   AND ITE.PENDENTE = 'S'
   AND PRO.ORIGPROD IN (1, 2, 6, 7)
   AND CAB.DTPREVENT IS NOT NULL
   AND TRUNC(CAB.DTPREVENT) - TRUNC(SYSDATE) BETWEEN 0 AND P.DIAS
 ORDER BY CAB.DTPREVENT, CAB.NUNOTA, G.CODGRUPO;
