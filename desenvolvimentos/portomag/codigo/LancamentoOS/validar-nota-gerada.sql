-- Somente leitura, executar APOS a conclusao da acao.
-- Informar a chave da linha de origem em :NUNOTA_ORIGEM e :SEQUENCIA_ORIGEM.
SELECT A.NUNOTA AS NUNOTA_ORIGEM, A.SEQUENCIA, A.NUOS,
       A.VLRSERVICO AS VALOR_ATIVIDADE, A.OBSSERVICO AS OBS_ATIVIDADE,
       C.NUNOTA AS NOTA_ENCONTRADA, C.NUMNOTA, C.CODEMP, C.CODPARC,
       C.CODTIPOPER, C.DHTIPOPER, C.TIPMOV, C.STATUSNOTA, C.VLRNOTA,
       C.OBSERVACAO, C.VLRNOTA - ROUND(A.VLRSERVICO, 2) AS DIFERENCA_VALOR
  FROM AD_APONTAMENTO A
  LEFT JOIN TGFCAB C ON C.NUNOTA = A.NUOS
 WHERE A.NUNOTA = :NUNOTA_ORIGEM AND A.SEQUENCIA = :SEQUENCIA_ORIGEM;

SELECT I.NUNOTA, I.SEQUENCIA, I.CODPROD, I.PRODUTONFE, I.AD_PRODINST,
       I.QTDNEG, I.VLRUNIT, I.VLRTOT,
       I.CODVOL, I.AD_SITEDEF, I.AD_NOMECID, I.AD_UF, I.AD_CEP
  FROM TGFITE I
 WHERE I.NUNOTA = (SELECT A.NUOS FROM AD_APONTAMENTO A
                   WHERE A.NUNOTA = :NUNOTA_ORIGEM AND A.SEQUENCIA = :SEQUENCIA_ORIGEM);

-- Conferir que outras linhas nao foram vinculadas indevidamente.
SELECT NUNOTA, SEQUENCIA, NUOS
  FROM AD_APONTAMENTO
 WHERE NUNOTA = :NUNOTA_ORIGEM
 ORDER BY SEQUENCIA;
