-- Somente leitura. As constraints devem estar ENABLED/VALIDATED com estas colunas.
SELECT C.TABLE_NAME,C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE,C.STATUS,C.VALIDATED,
       CC.COLUMN_NAME,CC.POSITION
FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC
  ON CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME AND CC.TABLE_NAME=C.TABLE_NAME
WHERE C.TABLE_NAME IN ('ZPM_PEDREC','ZPM_PEDITE')
ORDER BY C.TABLE_NAME,C.CONSTRAINT_NAME,CC.POSITION;

SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_LENGTH,DATA_PRECISION,DATA_SCALE,NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN ('ZPM_PEDREC','ZPM_PEDITE')
ORDER BY TABLE_NAME,COLUMN_ID;

-- Informar ID de homologacao. Nao consulta pedidos de outros registros.
SELECT P.ID,P.NUMPED,P.SITUACAO,P.TOTALPDF,COUNT(I.SEQEXT) AS QTD_ITENS,SUM(I.TOTALITEM) AS SOMA_ITENS
FROM ZPM_PEDREC P LEFT JOIN ZPM_PEDITE I ON I.IDPED=P.ID
WHERE P.ID=:IDPED
GROUP BY P.ID,P.NUMPED,P.SITUACAO,P.TOTALPDF;
