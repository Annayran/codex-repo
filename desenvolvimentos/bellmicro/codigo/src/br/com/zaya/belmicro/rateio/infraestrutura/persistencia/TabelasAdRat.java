package br.com.zaya.belmicro.rateio.infraestrutura.persistencia;

import br.com.zaya.belmicro.rateio.aplicacao.dto.OrigemCanonica;
import br.com.zaya.belmicro.rateio.aplicacao.porta.SimulacaoRepository.Trabalho;
import br.com.zaya.belmicro.rateio.infraestrutura.jdbc.TabelaRateio;
import java.util.List;
import java.util.Map;

/** Infrastructure bridge: all writes are to the additional tables, never TGFFIN/TGFCAB. */
public interface TabelasAdRat {
    <T> T emTransacao(OrigemCanonica origem, Trabalho<T> trabalho);
    List<Map<String,Object>> selecionar(TabelaRateio tabela, Map<String,Object> filtro);
    /** Select only the structured event fragments matching a SHA-256 request key prefix. */
    List<Map<String,Object>> eventosSolicitacao(String hashChave);
    /** Returns the row with native autogenerated keys. */
    Map<String,Object> inserir(TabelaRateio tabela, Map<String,Object> campos);
    void atualizar(TabelaRateio tabela, Map<String,Object> chave, Map<String,Object> campos);
    void excluirFilhos(TabelaRateio tabela, long simulacaoId);
}
