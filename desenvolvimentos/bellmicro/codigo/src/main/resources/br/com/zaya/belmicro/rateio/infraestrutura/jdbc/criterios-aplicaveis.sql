SELECT C.CODCRITERIO, C.DESCRICAO, C.MODALIDADE, V.SEQUENCIA, V.NROVERSAO
FROM AD_RATCRI C
JOIN AD_RATVER V ON V.CODCRITERIO = C.CODCRITERIO
WHERE C.ATIVO = 'S' AND C.APROVADO = 'S' AND V.SITUACAO = 'A'
  AND C.CODEMPORIG = ? AND C.CODNAT = ?
  AND (C.CODPARC IS NULL OR C.CODPARC = ?)
  AND (C.CODTIPOPER IS NULL OR C.CODTIPOPER = ?)
  AND C.DTVIGENCIAINI <= ?
  AND (C.DTVIGENCIAFIM IS NULL OR C.DTVIGENCIAFIM >= ?)
  AND V.DTVIGENCIAINI <= ?
  AND (V.DTVIGENCIAFIM IS NULL OR V.DTVIGENCIAFIM >= ?)
ORDER BY C.CODCRITERIO, V.SEQUENCIA
