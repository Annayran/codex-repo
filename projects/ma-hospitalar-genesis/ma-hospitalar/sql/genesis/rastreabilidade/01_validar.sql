SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_LENGTH,CHAR_LENGTH,NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('AD_GENAPICTRL','AD_GENREQLOG')
   OR (TABLE_NAME='AD_GENMOVEST' AND COLUMN_NAME IN ('ETAPA_ATUAL','ENTIDADE_BLOQ','ULT_OPERACAO','PROX_TENTATIVA'))
ORDER BY TABLE_NAME,COLUMN_ID;

SELECT CHAVE_MOVIMENTO,COUNT(*) QUANTIDADE
FROM AD_GENMOVEST WHERE CHAVE_MOVIMENTO LIKE 'API|%'
GROUP BY CHAVE_MOVIMENTO HAVING COUNT(*)>1;

SELECT TIPO_MOVIMENTO,COUNT(*) QUANTIDADE
FROM AD_GENMOVEST WHERE CHAVE_MOVIMENTO LIKE 'API|%' GROUP BY TIPO_MOVIMENTO;
