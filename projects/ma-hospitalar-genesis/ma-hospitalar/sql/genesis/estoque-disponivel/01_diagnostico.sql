-- SOMENTE LEITURA. Nenhum resultado autoriza exclusao automatica de cadastros.

-- 1. Confirmar campos customizados e tamanhos no ambiente.
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,CHAR_LENGTH,CHAR_USED
FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME='TGFPRO' AND COLUMN_NAME='HSP_IDEXTERNO')
   OR (TABLE_NAME='AD_CENTPARAMEMP' AND COLUMN_NAME IN ('NUPAR','CODEMP'))
   OR (TABLE_NAME='AD_CENTPARAMLOC' AND COLUMN_NAME IN ('NUPAR','CODLOCAL'))
   OR (TABLE_NAME='AD_GENESTCTRL' AND COLUMN_NAME IN ('CODIGOEXTERNO','STATUS'))
ORDER BY TABLE_NAME,COLUMN_NAME;

-- 2. Escopo utilizado.
SELECT NUPAR,CODEMP FROM AD_CENTPARAMEMP WHERE NUPAR=1 ORDER BY CODEMP;
SELECT NUPAR,CODLOCAL FROM AD_CENTPARAMLOC WHERE NUPAR=1 ORDER BY CODLOCAL;

-- 3. Disponivel separado por produto e tipo. EXISTS nao multiplica linhas.
SELECT E.CODPROD,TRIM(P.HSP_IDEXTERNO) HSP_IDEXTERNO,E.TIPO,
       SUM(NVL(E.ESTOQUE,0)) FISICO,SUM(NVL(E.RESERVADO,0)) RESERVADO,
       SUM(NVL(E.ESTOQUE,0)-NVL(E.RESERVADO,0)) DISPONIVEL
FROM TGFEST E JOIN TGFPRO P ON P.CODPROD=E.CODPROD
WHERE E.TIPO IN ('P','T')
  AND EXISTS (SELECT 1 FROM AD_CENTPARAMEMP C WHERE C.NUPAR=1 AND C.CODEMP=E.CODEMP)
  AND EXISTS (SELECT 1 FROM AD_CENTPARAMLOC C WHERE C.NUPAR=1 AND C.CODLOCAL=E.CODLOCAL)
GROUP BY E.CODPROD,TRIM(P.HSP_IDEXTERNO),E.TIPO ORDER BY E.CODPROD,E.TIPO;

-- 4. Fontes repetidas: nao significa duplicidade comprovada na API.
SELECT UPPER(TRIM(HSP_IDEXTERNO)) CHAVE,COUNT(*) PRODUTOS
FROM TGFPRO WHERE TRIM(HSP_IDEXTERNO) IS NOT NULL
GROUP BY UPPER(TRIM(HSP_IDEXTERNO)) HAVING COUNT(*)>1;

-- 5. Controles antigos que precisam de conciliacao; nao limpar ID automaticamente.
SELECT P.CODPROD,TRIM(P.HSP_IDEXTERNO) HSP_IDEXTERNO,
       C.CODIGOEXTERNO CODIGO_CONTROLE,C.IDGENESIS,C.STATUS,C.OPERACAO
FROM TGFPRO P LEFT JOIN AD_GENESTCTRL C ON C.CODPROD=P.CODPROD
WHERE (P.ATIVO='S' AND UPPER(COALESCE(TRIM(P.HSP_TIPOPRODUTO),TRIM(P.AD_TIPOPRODUTO))) IN ('M2','M3','SV'))
   OR C.CODPROD IS NOT NULL
ORDER BY P.CODPROD;

-- 6. Produtos cujo codigo fonte nao cabe na coluna atual do controle.
SELECT P.CODPROD,LENGTH(TRIM(P.HSP_IDEXTERNO)) CARACTERES,LENGTHB(TRIM(P.HSP_IDEXTERNO)) BYTES
FROM TGFPRO P JOIN USER_TAB_COLUMNS C ON C.TABLE_NAME='AD_GENESTCTRL' AND C.COLUMN_NAME='CODIGOEXTERNO'
WHERE (C.CHAR_USED='B' AND LENGTHB(TRIM(P.HSP_IDEXTERNO))>C.DATA_LENGTH)
   OR (C.CHAR_USED='C' AND LENGTH(TRIM(P.HSP_IDEXTERNO))>C.CHAR_LENGTH);

-- 7. Mais de um ID criado por POST para um produto: indicio historico, validar na API.
SELECT REGEXP_SUBSTR(CONTEXTO,'CODPROD=([0-9]+)',1,1,NULL,1) CODPROD,
       COUNT(DISTINCT IDRETORNO) IDS_CRIADOS
FROM AD_GENREQLOG
WHERE FLUXO='ESTOQUES_PRECOS' AND METODO='POST' AND HTTP_STATUS=201
  AND ENDPOINT='/estoques/' AND IDRETORNO IS NOT NULL
GROUP BY REGEXP_SUBSTR(CONTEXTO,'CODPROD=([0-9]+)',1,1,NULL,1)
HAVING COUNT(DISTINCT IDRETORNO)>1;

-- 8. IDs diferentes para produtos com a mesma identidade fonte.
SELECT UPPER(TRIM(P.HSP_IDEXTERNO)) CHAVE,COUNT(DISTINCT C.IDGENESIS) IDS_REMOTOS
FROM AD_GENESTCTRL C JOIN TGFPRO P ON P.CODPROD=C.CODPROD
WHERE TRIM(P.HSP_IDEXTERNO) IS NOT NULL AND C.IDGENESIS IS NOT NULL
GROUP BY UPPER(TRIM(P.HSP_IDEXTERNO)) HAVING COUNT(DISTINCT C.IDGENESIS)>1;
