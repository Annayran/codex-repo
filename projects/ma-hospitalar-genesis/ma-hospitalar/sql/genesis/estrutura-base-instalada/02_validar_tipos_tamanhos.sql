-- Execute antes e depois de 01_ajustar_tipos_tamanhos.sql.
-- O resultado deve ser comparado com a modelagem aprovada.

SELECT TABLE_NAME,
       COLUMN_ID,
       COLUMN_NAME,
       DATA_TYPE,
       CASE
           WHEN DATA_TYPE IN ('VARCHAR2', 'CHAR') THEN CHAR_LENGTH
           WHEN DATA_TYPE = 'NUMBER' THEN DATA_PRECISION
           ELSE DATA_LENGTH
       END AS TAMANHO,
       DATA_SCALE,
       CHAR_USED,
       NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN (
       'AD_GENBASE',
       'AD_GENDOMINIO',
       'AD_GENCLIENTE',
       'AD_GENSECTOR',
       'AD_GENMATERIAL',
       'AD_GENEMPRESA',
       'AD_GENMODELO',
       'AD_GENITEMMAT'
 )
 ORDER BY TABLE_NAME, COLUMN_ID;

-- Quantidade esperada de campos por tabela.
SELECT TABLE_NAME,
       COUNT(*) AS TOTAL_CAMPOS,
       CASE TABLE_NAME
           WHEN 'AD_GENBASE' THEN 10
           WHEN 'AD_GENDOMINIO' THEN 9
           WHEN 'AD_GENCLIENTE' THEN 21
           WHEN 'AD_GENSECTOR' THEN 12
           WHEN 'AD_GENMATERIAL' THEN 12
           WHEN 'AD_GENEMPRESA' THEN 13
           WHEN 'AD_GENMODELO' THEN 13
           WHEN 'AD_GENITEMMAT' THEN 30
       END AS TOTAL_ESPERADO
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME LIKE 'AD_GEN%'
   AND TABLE_NAME IN (
       'AD_GENBASE', 'AD_GENDOMINIO', 'AD_GENCLIENTE', 'AD_GENSECTOR',
       'AD_GENMATERIAL', 'AD_GENEMPRESA', 'AD_GENMODELO', 'AD_GENITEMMAT'
   )
 GROUP BY TABLE_NAME
 ORDER BY TABLE_NAME;

-- Textos longos: todos devem retornar DATA_TYPE = CLOB.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE
  FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'AD_GENBASE' AND COLUMN_NAME = 'OBSERVACAO')
    OR (TABLE_NAME IN (
        'AD_GENDOMINIO', 'AD_GENCLIENTE', 'AD_GENSECTOR', 'AD_GENMATERIAL',
        'AD_GENEMPRESA', 'AD_GENMODELO', 'AD_GENITEMMAT'
    ) AND COLUMN_NAME = 'MENSAGEMCONC')
 ORDER BY TABLE_NAME;

