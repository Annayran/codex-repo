-- Campos de texto longo devem ser CLOB. O Oracle nao permite conversao direta
-- de VARCHAR2 para CLOB por ALTER TABLE MODIFY (ORA-22858). Os comandos abaixo
-- preservam os valores usando uma coluna temporaria. Execute este arquivo uma
-- unica vez; as colunas temporarias nao podem existir antes da execucao.

ALTER TABLE AD_GENBASE ADD (OBSERVACAO_TMP CLOB);
UPDATE AD_GENBASE SET OBSERVACAO_TMP = OBSERVACAO;
ALTER TABLE AD_GENBASE DROP COLUMN OBSERVACAO;
ALTER TABLE AD_GENBASE RENAME COLUMN OBSERVACAO_TMP TO OBSERVACAO;

