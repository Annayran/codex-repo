CREATE OR REPLACE VIEW AD_VW_GENESIS_ESTOQUE AS
SELECT
    -- Empresa
    EMP.CODEMP AS CODEMP,
    EMP.NOMEFANTASIA AS NOMEFANTASIA,
    EMP.RAZAOSOCIAL AS RAZAO_EMPRESA,
    EMP.CGC AS CNPJ_EMPRESA,

    -- Nota
    CAB.NUNOTA AS NUNOTA,
    CAB.NUMNOTA AS NUMNOTA,
    CAB.DTNEG AS DTNEG,
    CAB.DTNEG AS DTINSTALACAO,
    CAB.CODTIPOPER AS CODTIPOPER,
    ITE.SEQUENCIA AS SEQUENCIA,

    -- Parceiro
    PAR.CODPARC AS CODPARC,
    PAR.NOMEPARC AS NOMEPARC,
    PAR.RAZAOSOCIAL AS RAZAO_PARCEIRO,
    PAR.CGC_CPF AS CNPJ_CPF_PARCEIRO,
    CID.NOMECID AS CIDADE,
    PAR.CEP AS CEP,
    TRIM(
        ENDP.TIPO || ' ' ||
        ENDP.NOMEEND || ', ' ||
        PAR.NUMEND || ' ' ||
        PAR.COMPLEMENTO || ' - ' ||
        BAI.NOMEBAI || ' - ' ||
        CID.NOMECID || ' - ' ||
        UFS.UF || ' - ' ||
        PAR.CEP
    ) AS ENDERECO,
    PAR.TELEFONE AS TELEFONE,
    CASE
        WHEN PAR.ATIVO = 'S' THEN 'Ativo'
        WHEN PAR.ATIVO = 'N' THEN 'Inativo'
        ELSE 'Ativo'
    END AS PARC_STATUS,

    -- Produto
    PRO.CODPROD AS CODPROD,
    PRO.DESCRPROD AS DESCRPROD,
    PRO.CODPROD || ' - ' || PRO.DESCRPROD AS PRODUTO,
    GRU.CODGRUPOPROD AS CODGRUPOPROD,
    GRU.DESCRGRUPOPROD AS DESCRGRUPOPROD,
    GRU.CODGRUPOPROD || ' - ' || GRU.DESCRGRUPOPROD AS GRUPO_PRODUTO,
    ITE.VLRUNIT AS VLRUNIT,
    ITE.CODLOCALORIG AS CODLOCALORIG,
    LOC.DESCRLOCAL AS DESCRLOCAL,
    PRO.MARCA AS MARCA,
    PRO.CODANVISA AS CODANVISA,
    SER.SERIE AS SERIE,
    SER.SERIEFAB AS SERIE_FABRICANTE,
    SER.AVARIADO AS AVARIADO,
    SER.ATUALESTOQUE AS SER_ATUAL_ESTOQUE,
    CASE
        WHEN PRO.ATIVO = 'S' THEN 'Ativo'
        WHEN PRO.ATIVO = 'N' THEN 'Inativo'
        ELSE 'Ativo'
    END AS PROD_STATUS,

    -- Movimento: permanece com a regra original da TGFESE
    CASE
        WHEN NVL(ESE.QTDENTRADAS, 0) > 0 THEN 'ENTRADA'
        WHEN NVL(ESE.QTDSAIDAS, 0) > 0 THEN 'SAIDA'
        WHEN NVL(ESE.ATUALESTOQUE, 0) > 0 THEN 'ENTRADA'
        WHEN NVL(ESE.ATUALESTOQUE, 0) < 0 THEN 'SAIDA'
    END AS TIPO,

    -- Poder: permanece com a regra original da TGFEST
    CASE
        WHEN NVL(EST.CODPARC, 0) = 0 THEN 'PROPRIO'
        ELSE 'TERCEIRO'
    END AS PODER,

    -- Tipo do estoque: unica classificacao afetada pelo CNPJ do parceiro
    CASE
        WHEN PAR.CGC_CPF IS NULL THEN 'NAO_CLASSIFICADO'
        WHEN EXISTS (
            SELECT 1
              FROM TSIEMP EMPDOC
             WHERE LPAD(
                       REGEXP_REPLACE(TO_CHAR(EMPDOC.CGC), '[^0-9]', ''),
                       14,
                       '0'
                   ) =
                   LPAD(
                       REGEXP_REPLACE(TO_CHAR(PAR.CGC_CPF), '[^0-9]', ''),
                       14,
                       '0'
                   )
        ) THEN 'PROPRIO'
        ELSE 'TERCEIRO'
    END AS TIPO_ESTOQUE,

    ITE.AD_GARANTIA AS GARANTIA_MESES,
    SER.AD_STATUSEST AS STATUS_ESTOQUE,
    CASE SER.AD_STATUSEST
        WHEN 'O' THEN 'Operacional'
        WHEN 'A' THEN 'Alienado'
        WHEN 'I' THEN 'Inoperante'
        WHEN 'V' THEN 'Validacao'
        WHEN 'D' THEN 'Desativado'
        WHEN 'R' THEN 'Restricoes'
    END AS STATUS_ESTOQUE_DESC,

    EMP.CODEMP || '|' ||
    CAB.NUNOTA || '|' ||
    ITE.SEQUENCIA || '|' ||
    PRO.CODPROD || '|' ||
    SER.SERIE AS CHAVE_MOVIMENTO

FROM TGFCAB CAB

JOIN TGFITE ITE
  ON ITE.NUNOTA = CAB.NUNOTA

JOIN TGFPRO PRO
  ON PRO.CODPROD = ITE.CODPROD

LEFT JOIN TGFGRU GRU
  ON GRU.CODGRUPOPROD = PRO.CODGRUPOPROD

JOIN TGFPAR PAR
  ON PAR.CODPARC = CAB.CODPARC

JOIN TSIEMP EMP
  ON EMP.CODEMP = CAB.CODEMP

LEFT JOIN TSIEND ENDP
  ON ENDP.CODEND = PAR.CODEND

LEFT JOIN TSIBAI BAI
  ON BAI.CODBAI = PAR.CODBAI

LEFT JOIN TSICID CID
  ON CID.CODCID = PAR.CODCID

LEFT JOIN TSIUFS UFS
  ON TO_CHAR(UFS.CODUF) = TO_CHAR(CID.UF)

LEFT JOIN TGFLOC LOC
  ON LOC.CODLOCAL = ITE.CODLOCALORIG

-- TGFEST pode possuir mais de uma posicao para produto/local/controle.
-- Consolida antes do JOIN para nao multiplicar o movimento da nota.
LEFT JOIN (
    SELECT
        CODEMP,
        CODPROD,
        CODLOCAL,
        TO_CHAR(CONTROLE) AS CONTROLE,
        MAX(CASE WHEN NVL(CODPARC, 0) <> 0 THEN CODPARC END) AS CODPARC
    FROM TGFEST
    GROUP BY CODEMP, CODPROD, CODLOCAL, TO_CHAR(CONTROLE)
) EST
  ON EST.CODEMP = CAB.CODEMP
 AND EST.CODPROD = ITE.CODPROD
 AND EST.CODLOCAL = ITE.CODLOCALORIG
 AND TO_CHAR(EST.CONTROLE) = TO_CHAR(ITE.CONTROLE)

LEFT JOIN TGFSER SER
  ON SER.NUNOTA = ITE.NUNOTA
 AND SER.CODPROD = ITE.CODPROD
 AND SER.SEQUENCIA = ITE.SEQUENCIA

-- TGFESE pode retornar varias linhas para a mesma chave operacional.
-- Soma os indicadores antes do JOIN e preserva a regra de ENTRADA/SAIDA.
LEFT JOIN (
    SELECT
        CODEMP,
        CODPROD,
        CODLOCALORIG,
        TO_CHAR(CONTROLE) AS CONTROLE,
        CODTIPOPER,
        SUM(NVL(QTDENTRADAS, 0)) AS QTDENTRADAS,
        SUM(NVL(QTDSAIDAS, 0)) AS QTDSAIDAS,
        SUM(NVL(ATUALESTOQUE, 0)) AS ATUALESTOQUE
    FROM TGFESE
    GROUP BY CODEMP, CODPROD, CODLOCALORIG, TO_CHAR(CONTROLE), CODTIPOPER
) ESE
  ON ESE.CODEMP = CAB.CODEMP
 AND ESE.CODPROD = ITE.CODPROD
 AND ESE.CODLOCALORIG = ITE.CODLOCALORIG
 AND TO_CHAR(ESE.CONTROLE) = TO_CHAR(ITE.CONTROLE)
 AND ESE.CODTIPOPER = CAB.CODTIPOPER

WHERE EXISTS (
    SELECT 1
      FROM AD_CENTPARAMTOP CPT
     WHERE CPT.NUPAR = 1
       AND CPT.CODTIPOPER = CAB.CODTIPOPER
)
AND UPPER(COALESCE(TRIM(PRO.HSP_TIPOPRODUTO), TRIM(PRO.AD_TIPOPRODUTO))) = 'M1'
AND SER.SERIE IS NOT NULL
