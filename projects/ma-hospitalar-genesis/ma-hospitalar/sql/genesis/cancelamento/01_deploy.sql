SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_LENGTH,NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('AD_GENEXCFILA','AD_GENMOVEST','AD_GENITEMMAT')
  AND (TABLE_NAME='AD_GENEXCFILA' OR COLUMN_NAME IN ('NUNOTA','ORIGEM_ITEM'))
ORDER BY TABLE_NAME,COLUMN_ID;

SELECT C.TABLE_NAME,C.CONSTRAINT_TYPE,CC.COLUMN_NAME
FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
WHERE C.TABLE_NAME='AD_GENEXCFILA' AND C.CONSTRAINT_TYPE IN ('P','R')
ORDER BY C.CONSTRAINT_TYPE,CC.POSITION;
