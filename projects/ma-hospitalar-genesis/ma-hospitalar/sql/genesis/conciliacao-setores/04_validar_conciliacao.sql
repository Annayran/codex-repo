-- 1. Resumo do resultado desta conciliacao.
SELECT
    DBMS_LOB.SUBSTR(MENSAGEMCONC, 200, 1) AS RESULTADO,
    STATUSCONC,
    COUNT(*) AS QUANTIDADE
FROM AD_GENSECTOR
WHERE IDBASE = 1
  AND DBMS_LOB.SUBSTR(MENSAGEMCONC, 200, 1) LIKE 'CONC_SETOR_20260910:%'
GROUP BY DBMS_LOB.SUBSTR(MENSAGEMCONC, 200, 1), STATUSCONC
ORDER BY RESULTADO

-- 2. Deve retornar zero: cliente nao pode possuir mais de um setor padrao conciliado.
SELECT IDCLIENTEGEN, CODPARC, COUNT(*) AS QUANTIDADE
FROM AD_GENSECTOR
WHERE IDBASE = 1
  AND STATUSCONC = 'CONCILIADO'
  AND PADRAO = 'S'
GROUP BY IDCLIENTEGEN, CODPARC
HAVING COUNT(*) > 1

-- 3. Deve retornar zero: setor conciliado precisa ter cliente e parceiro.
SELECT COUNT(*) AS SETORES_CONCILIADOS_INCOMPLETOS
FROM AD_GENSECTOR
WHERE IDBASE = 1
  AND STATUSCONC = 'CONCILIADO'
  AND (IDCLIENTEGEN IS NULL OR CODPARC IS NULL OR IDGENESIS IS NULL)

-- 4. Caso do cliente Genesis 95 deve apresentar CODPARC=1179, PADRAO=S e CONCILIADO.
SELECT IDREGSET, IDGENESIS, IDCLIENTEGEN, CODPARC, NOME, PADRAO, STATUSCONC,
       DBMS_LOB.SUBSTR(MENSAGEMCONC, 200, 1) AS MENSAGEMCONC
FROM AD_GENSECTOR
WHERE IDBASE = 1
  AND IDCLIENTEGEN = 95

-- 5. Candidatos da view que continuam sem setor resolvivel.
SELECT V.CODPARC, C.IDGENESIS AS IDCLIENTEGEN, COUNT(*) AS MOVIMENTOS
FROM AD_VW_GENESIS_ESTOQUE V
JOIN AD_GENCLIENTE C
  ON C.IDBASE = 1
 AND C.CODPARC = V.CODPARC
 AND C.STATUSCONC = 'CONCILIADO'
LEFT JOIN AD_GENSECTOR S
  ON S.IDBASE = 1
 AND S.IDCLIENTEGEN = C.IDGENESIS
 AND S.CODPARC = V.CODPARC
 AND S.STATUSCONC = 'CONCILIADO'
WHERE V.SERIE IS NOT NULL
  AND S.IDGENESIS IS NULL
GROUP BY V.CODPARC, C.IDGENESIS
ORDER BY MOVIMENTOS DESC

