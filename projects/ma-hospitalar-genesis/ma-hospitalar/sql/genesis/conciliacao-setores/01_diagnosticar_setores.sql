-- 1. Resumo de todos os setores pendentes e a possibilidade de conciliacao.
WITH CLIENTES AS (
    SELECT
        IDGENESIS,
        COUNT(*) AS QTD_CLIENTES,
        SUM(CASE WHEN CODPARC IS NOT NULL AND STATUSCONC = 'CONCILIADO' THEN 1 ELSE 0 END) AS QTD_CLIENTES_CONC,
        MAX(CASE WHEN CODPARC IS NOT NULL AND STATUSCONC = 'CONCILIADO' THEN CODPARC END) AS CODPARC,
        MAX(RAZAOSOCIAL) AS RAZAOSOCIAL,
        MAX(NOMEFANTASIA) AS NOMEFANTASIA
    FROM AD_GENCLIENTE
    WHERE IDBASE = 1
    GROUP BY IDGENESIS
), BASE AS (
    SELECT
        S.IDREGSET,
        S.IDGENESIS,
        S.IDCLIENTEGEN,
        S.NOME,
        S.CODPARC AS CODPARC_ATUAL,
        S.PADRAO,
        S.STATUSCONC,
        C.CODPARC AS CODPARC_CLIENTE,
        C.QTD_CLIENTES,
        C.QTD_CLIENTES_CONC,
        CASE
            WHEN REGEXP_REPLACE(UPPER(TRIM(S.NOME)), '[^[:alnum:]]', '') =
                 REGEXP_REPLACE(UPPER(TRIM(C.RAZAOSOCIAL)), '[^[:alnum:]]', '')
              OR REGEXP_REPLACE(UPPER(TRIM(S.NOME)), '[^[:alnum:]]', '') =
                 REGEXP_REPLACE(UPPER(TRIM(C.NOMEFANTASIA)), '[^[:alnum:]]', '')
            THEN 1 ELSE 0
        END AS NOME_CORRESPONDE
    FROM AD_GENSECTOR S
    LEFT JOIN CLIENTES C ON C.IDGENESIS = S.IDCLIENTEGEN
    WHERE S.IDBASE = 1
), ANALISE AS (
    SELECT
        B.*,
        COUNT(*) OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_SETORES,
        SUM(B.NOME_CORRESPONDE) OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_NOMES_CORRESPONDENTES,
        SUM(CASE WHEN B.STATUSCONC = 'CONCILIADO' AND B.CODPARC_ATUAL IS NOT NULL THEN 1 ELSE 0 END)
            OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_SETORES_CONC
    FROM BASE B
), CLASSIFICACAO AS (
    SELECT
        A.*,
        CASE
            WHEN A.IDCLIENTEGEN IS NULL THEN 'SEM_CLIENTE_GENESIS'
            WHEN NVL(A.QTD_CLIENTES, 0) = 0 THEN 'CLIENTE_NAO_LOCALIZADO'
            WHEN A.QTD_CLIENTES > 1 THEN 'CLIENTE_GENESIS_DUPLICADO'
            WHEN A.QTD_CLIENTES_CONC <> 1 OR A.CODPARC_CLIENTE IS NULL THEN 'CLIENTE_NAO_CONCILIADO'
            WHEN A.QTD_SETORES_CONC > 0 THEN 'JA_POSSUI_SETOR_CONCILIADO'
            WHEN A.QTD_SETORES = 1 THEN 'CORRESPONDENCIA_UNICA'
            WHEN A.QTD_NOMES_CORRESPONDENTES = 1 AND A.NOME_CORRESPONDE = 1 THEN 'CORRESPONDENCIA_NOME_UNICA'
            WHEN A.QTD_NOMES_CORRESPONDENTES = 1 THEN 'SETOR_NAO_SELECIONADO'
            WHEN A.QTD_NOMES_CORRESPONDENTES > 1 THEN 'NOME_AMBIGUO'
            ELSE 'MULTIPLOS_SETORES_SEM_NOME'
        END AS SITUACAO
    FROM ANALISE A
)
SELECT SITUACAO, COUNT(*) AS QUANTIDADE
FROM CLASSIFICACAO
WHERE NVL(STATUSCONC, 'PENDENTE') = 'PENDENTE'
GROUP BY SITUACAO
ORDER BY SITUACAO

-- 2. Detalhamento somente das correspondencias que podem ser aplicadas.
WITH CLIENTES AS (
    SELECT IDGENESIS, COUNT(*) AS QTD_CLIENTES,
           SUM(CASE WHEN CODPARC IS NOT NULL AND STATUSCONC = 'CONCILIADO' THEN 1 ELSE 0 END) AS QTD_CLIENTES_CONC,
           MAX(CASE WHEN CODPARC IS NOT NULL AND STATUSCONC = 'CONCILIADO' THEN CODPARC END) AS CODPARC,
           MAX(RAZAOSOCIAL) AS RAZAOSOCIAL, MAX(NOMEFANTASIA) AS NOMEFANTASIA
    FROM AD_GENCLIENTE WHERE IDBASE = 1 GROUP BY IDGENESIS
), BASE AS (
    SELECT S.IDREGSET, S.IDGENESIS, S.IDCLIENTEGEN, S.NOME, S.CODPARC AS CODPARC_ATUAL,
           S.PADRAO, S.STATUSCONC, C.CODPARC AS CODPARC_CLIENTE, C.QTD_CLIENTES, C.QTD_CLIENTES_CONC,
           CASE WHEN REGEXP_REPLACE(UPPER(TRIM(S.NOME)), '[^[:alnum:]]', '') IN (
                    REGEXP_REPLACE(UPPER(TRIM(C.RAZAOSOCIAL)), '[^[:alnum:]]', ''),
                    REGEXP_REPLACE(UPPER(TRIM(C.NOMEFANTASIA)), '[^[:alnum:]]', '')
                ) THEN 1 ELSE 0 END AS NOME_CORRESPONDE
    FROM AD_GENSECTOR S LEFT JOIN CLIENTES C ON C.IDGENESIS = S.IDCLIENTEGEN
    WHERE S.IDBASE = 1
), A AS (
    SELECT B.*, COUNT(*) OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_SETORES,
           SUM(B.NOME_CORRESPONDE) OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_NOMES,
           SUM(CASE WHEN B.STATUSCONC = 'CONCILIADO' AND B.CODPARC_ATUAL IS NOT NULL THEN 1 ELSE 0 END)
               OVER (PARTITION BY B.IDCLIENTEGEN) AS QTD_CONC
    FROM BASE B
)
SELECT IDREGSET, IDGENESIS, IDCLIENTEGEN, CODPARC_CLIENTE AS NOVO_CODPARC, NOME,
       CASE WHEN QTD_SETORES = 1 THEN 'CORRESPONDENCIA_UNICA' ELSE 'CORRESPONDENCIA_NOME_UNICA' END AS SITUACAO
FROM A
WHERE NVL(STATUSCONC, 'PENDENTE') = 'PENDENTE'
  AND QTD_CLIENTES = 1
  AND QTD_CLIENTES_CONC = 1
  AND CODPARC_CLIENTE IS NOT NULL
  AND QTD_CONC = 0
  AND (QTD_SETORES = 1 OR (QTD_NOMES = 1 AND NOME_CORRESPONDE = 1))
ORDER BY IDCLIENTEGEN, IDGENESIS

-- 3. Conferencia direta do caso observado no log.
SELECT S.IDREGSET, S.IDGENESIS, S.IDCLIENTEGEN, S.CODPARC, S.NOME,
       S.PADRAO, S.STATUSCONC, C.CODPARC AS CODPARC_CLIENTE,
       C.RAZAOSOCIAL, C.NOMEFANTASIA
FROM AD_GENSECTOR S
LEFT JOIN AD_GENCLIENTE C
  ON C.IDBASE = S.IDBASE
 AND C.IDGENESIS = S.IDCLIENTEGEN
WHERE S.IDBASE = 1
  AND S.IDCLIENTEGEN = 95

