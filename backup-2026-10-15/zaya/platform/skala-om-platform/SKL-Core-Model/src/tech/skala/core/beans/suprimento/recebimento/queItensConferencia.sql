SELECT 
	CAB.CODPARC,
    ITE.CODPROD,
	COALESCE(PRO.REFERENCIA, TO_CHAR(PRO.CODPROD)) AS CODBARRA,
    PAP.CODPROPARC,
    PAP.CODBARRAPARC,
	ITE.CODEMP,
	ITE.CODLOCALORIG,
    ITE.CONTROLE,
	QTDEVOLPADRAO(ITE.CODPROD,ITE.QTDNEG,ITE.CODVOL) AS QTDNEG,
    ITE.CODVOL,
    ITE.QTDNEG AS QTDUNIDPAD,
	PRO.CODVOL AS CODVOLPAD,
    ITE.VLRUNIT, 
	EST.DTVAL, 
    EST.DTFABRICACAO,
    ITE.NUNOTA,
    ITE.SEQUENCIA
FROM TGFCAB CAB
JOIN TGFITE ITE ON (CAB.NUNOTA = ITE.NUNOTA) 
JOIN TGFPRO PRO ON (ITE.CODPROD = PRO.CODPROD)
JOIN TGFPAP PAP ON (CAB.CODPARC = PAP.CODPARC AND PAP.CODPROD = ITE.CODPROD AND PAP.SEQUENCIA = (SELECT MAX(T.SEQUENCIA) FROM TGFPAP T WHERE T.CODPARC = PAP.CODPARC AND T.CODPROD = PAP.CODPROD))
LEFT JOIN TGFEST EST ON (ITE.CODPROD = EST.CODPROD AND ITE.CODEMP = EST.CODEMP AND ITE.CONTROLE = EST.CONTROLE AND ITE.CODLOCALORIG = EST.CODLOCAL)
WHERE 
    CAB.NUNOTA = :NUNOTA
