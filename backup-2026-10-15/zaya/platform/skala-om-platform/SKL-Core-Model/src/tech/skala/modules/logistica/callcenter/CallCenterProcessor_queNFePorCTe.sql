SELECT 
	T.A AS CHAVENFE 
FROM 
(
	WITH STR AS (
		SELECT 
			CHAVE_NFS X, 
			';' DELIMITER 
		FROM CTE_CHAVE 
		WHERE CHAVE_CTE = :CHAVECTE
	)
	
	SELECT 
		SUBSTR(STR.X, INSTR(STR.DELIMITER||LTRIM(STR.X, STR.DELIMITER), STR.DELIMITER, 1, LEVEL)
		, INSTR(RTRIM(STR.X, STR.DELIMITER)||STR.DELIMITER, STR.DELIMITER, 1, LEVEL)-INSTR(STR.DELIMITER||LTRIM(STR.X, STR.DELIMITER), STR.DELIMITER, 1, LEVEL)) A FROM STR 
	CONNECT BY 
		LEVEL <= REGEXP_COUNT(STR.X,  STR.DELIMITER) + 1
)T 
WHERE 
	T.A IS NOT NULL
