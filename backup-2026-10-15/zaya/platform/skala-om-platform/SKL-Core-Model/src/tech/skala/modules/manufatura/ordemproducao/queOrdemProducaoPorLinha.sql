WITH OP AS
(
SELECT 
	IPRC.IDIPROC,
	WXIP.CODWCP,
	IPRC.IDPROC,
	IPRC.DHINC,
	IPRC.CODPLP,
	IPRC.NROLOTE,
	IPRC.STATUSPROC,
	IPA.CODPRODPA,
	PA.DESCRPROD AS DESCRPRODPA,
	IPA.CONTROLEPA,
	IPA.QTDPRODUZIR,
	IPA.DTFAB,
	IPA.DTVAL,
	IPA.CONCLUIDO,
	IATV.IDEFX,
	ATV.OPERCQ,
	IATV.DHFINAL
FROM TPRIPROC IPRC 
JOIN TPRWXIP WXIP ON (IPRC.IDIPROC = WXIP.IDIPROC)
LEFT OUTER JOIN TPRIATV IATV ON (IPRC.IDIPROC = IATV.IDIPROC AND WXIP.IDEFX = IATV.IDEFX)
JOIN TPRATV ATV ON (WXIP.IDEFX = ATV.IDEFX AND ATV.OPERCQ IN ('N'))
JOIN TPRIPA IPA ON (IPRC.IDIPROC = IPA.IDIPROC)
JOIN TGFPRO PA ON (IPA.CODPRODPA = PA.CODPROD)
WHERE
	WXIP.CODWCP = :CODWCP
AND IPRC.STATUSPROC IN ('R','A')
AND IPA.CONCLUIDO = 'N'
AND IATV.DHFINAL IS NULL
AND IPRC.IDIPROC > 375460
ORDER BY IPRC.IDIPROC
)
SELECT * FROM OP WHERE ROWNUM = 1