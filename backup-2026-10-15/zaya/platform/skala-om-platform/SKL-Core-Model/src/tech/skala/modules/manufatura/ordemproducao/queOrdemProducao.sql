SELECT
	IPRC.IDIPROC,
	IPRC.IDPROC,
	IPRC.NROLOTE,
	IPA.CODPRODPA,
	IPA.CONTROLEPA,
	IATV.DHINICIO,
	IATV.DHFINAL,
	IPRC.STATUSPROC,
	IPA.QTDPRODUZIR
FROM TPRIPROC IPRC
LEFT JOIN TPRIATV IATV ON (IATV.IDIPROC = IPRC.IDIPROC)
JOIN TPRIPA IPA ON (IPRC.IDIPROC = IPA.IDIPROC)
JOIN TGFPRO PA ON (IPA.CODPRODPA = PA.CODPROD)
WHERE 
	IPRC.IDIPROC = :IDIPROC