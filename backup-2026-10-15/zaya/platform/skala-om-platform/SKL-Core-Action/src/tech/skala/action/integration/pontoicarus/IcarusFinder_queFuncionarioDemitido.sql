SELECT 
	this.CODEMP,
	this.CODFUNC,
	this.MATRICULA,
	IFUN.IDMUTUARIO,
	this.DTDEM,
	THIS.CODMOTDESLIGTRANSF,
	F_DESCROPC('TFPFUN','SITUACAO',this.SITUACAO) AS DESCRSITUACAO
FROM TFPFUN /* Funcionario */ this 
JOIN AD_PLTPIFUN IFUN ON (this.CODEMP = IFUN.CODEMP AND this.CODFUNC = IFUN.CODFUNC)
LEFT OUTER JOIN TFPMTD /* MotivosDesligamento */ MTD on (this.CODMOTDESLIGTRANSF = MTD.CODMOTDESLIG)
WHERE this.DTDEM IS NOT NULL;

SELECT this.MATRICULA, this.* 
FROM TFPFUN /* Funcionario */ this 
WHERE this.DTDEM IS NOT NULL AND EXISTS(SELECT 1 FROM AD_PLTPIFUN T WHERE T.CODEMP = this.CODEMP AND T.CODFUNC = this.CODFUNC)