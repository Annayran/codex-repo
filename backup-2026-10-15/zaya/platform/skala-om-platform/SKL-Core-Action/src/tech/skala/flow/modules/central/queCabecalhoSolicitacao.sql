SELECT 
	CAB.CODEMP, 
	CAB.OBSER, 
	CAB.CODUSU,
	ITE.CODNAT,
	ITE.CODTIPVENDA, 
	ITE.CODTIPOPER, 
	ITE.CODPARC,
	MIN (ITE.DTPREVENT) AS DTPREVENT, 
	(SELECT CODCENCUSPAD FROM TSIUSU WHERE CODUSU = CAB.CODUSU) AS CODCENCUSPAD, 
	(SELECT CODVEND FROM TSIUSU WHERE CODUSU = (SELECT NUMINT FROM TWFIVAR WHERE NOME = 'CODUSUCOMPRAS' AND IDINSTPRN = :IDINSTPRN)) AS COMPRADOR  
FROM 
	AD_PLTFLCABCOMPRAS CAB  
JOIN AD_PLTFLITEMAPROVADOS ITE ON CAB.IDINSTPRN = ITE.IDINSTPRN  
WHERE CAB.IDINSTPRN = :IDINSTPRN  
GROUP BY 
	CAB.CODEMP, 
	CAB.OBSER,
	CAB.CODUSU,
	ITE.CODNAT,
	ITE.CODTIPVENDA,
	ITE.CODTIPOPER,
	ITE.CODPARC