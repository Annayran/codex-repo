UPDATE TGFVOA
SET TIPGTINNFE = NVL((select MAX(T.TIPGTINNFE) from TGFVOA_EXP T where T.CODPROD = TGFVOA.CODPROD and T.CODVOL = TGFVOA.CODVOL), TIPGTINNFE)
, UNIDTRIB = NVL((select MAX(T.UNIDTRIB) from TGFVOA_EXP T where T.CODPROD = TGFVOA.CODPROD and T.CODVOL = TGFVOA.CODVOL), UNIDTRIB)
WHERE
	(CODPROD IN (select T.CODPROD from TGFVOA_EXP T))