SELECT ITE.*
FROM DLTGFITE ITE
JOIN TGFPRO PRO ON (ITE.CODPROD = PRO.CODPROD)
WHERE
	EXISTS(SELECT 1 FROM DWTGFCABCART_TMP_INC T WHERE T.NUNOTA = ITE.NUNOTA)
AND EXISTS (SELECT 1 FROM AD_PLTGFFAMGRU T WHERE PRO.CODGRUPOPROD = T.CODGRUPOPROD AND T.CODFAM != 8)
AND (PRO.CODGRUPOPROD BETWEEN 10000 AND 19899)
