INSERT INTO DWTGFITEENTP 
SELECT X.CODPROD, SUM (X.QTDPENDENTE) QTDPENDENTE, X.REFERENCIA
FROM (SELECT ITE.CODPROD,
			 (ITE.QTDNEG - ITE.QTDENTREGUE) AS QTDPENDENTE,
			 TRUNC (
				COALESCE (ITE.DTINICIO, COALESCE (CAB.DTFATUR, CAB.DTNEG)),
				'MM')
				REFERENCIA
		FROM TGFCAB CAB
		JOIN TGFITE ITE ON (CAB.NUNOTA = ITE.NUNOTA)
		JOIN TGFPRO PRO ON (PRO.CODPROD = ITE.CODPROD)
		WHERE 
			((CAB.TIPMOV = 'O') AND (ITE.PENDENTE = 'S') AND (CAB.STATUSNOTA = 'L'))
		AND COALESCE (CAB.DTFATUR, CAB.DTNEG) >= TRUNC (SYSDATE, 'YYYY')
		AND PRO.USOPROD IN ('M', 'T', 'E', '2', 'P')
		UNION ALL
	  SELECT ITE.CODPROD,
			 (ITE.QTDNEG - ITE.QTDENTREGUE) AS QTDPENDENTE,
			 TRUNC (
				COALESCE (ITE.DTINICIO, COALESCE (CABORIG.DTFATUR, CABORIG.DTNEG)),
				'MM')
				REFERENCIA 
		FROM TGFCAB CAB 
		JOIN TGFTOP TPO ON (CAB.CODTIPOPER = TPO.CODTIPOPER AND CAB.DHTIPOPER = TPO.DHALTER) 
		JOIN TGFITE ITE ON (CAB.NUNOTA = ITE.NUNOTA) 
		JOIN TGFPRO PRO ON (PRO.CODPROD = ITE.CODPROD)
		JOIN TGFVAR VAR ON (VAR.NUNOTA = ITE.NUNOTA AND VAR.SEQUENCIA = ITE.SEQUENCIA)
		JOIN TGFCAB CABORIG ON (CABORIG.NUNOTA = VAR.NUNOTAORIG)
		WHERE 
			((CAB.TIPMOV = 'C') AND (CAB.STATUSNOTA != 'L'))
		AND (TPO.ADIARATUALEST = 'S')
		AND COALESCE (CAB.DTFATUR, CAB.DTNEG) >= TRUNC (SYSDATE, 'YYYY')
		AND PRO.USOPROD IN ('M', 'T', 'E', '2', 'P')) X
GROUP BY X.CODPROD, X.REFERENCIA
