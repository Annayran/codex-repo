INSERT INTO AD_PLTGFENT (
	NUNOTA,
	CODEMP,
	ORDEMCARGA,
	DTLIMITEENTREGA,
	CODUSUINC,
	DHINC)
SELECT 
	:NUNOTA,
	(SELECT T.CODEMP FROM DLTGFCAB T WHERE T.NUNOTA = :NUNOTA) AS CODEMP,
	(SELECT T.ORDEMCARGA FROM DLTGFCAB T WHERE T.NUNOTA = :NUNOTA) AS ORDEMCARGA,
	CAL.DTLIMITEENTREGA,
	CAL.CODUSU,
	CAL.DHINCLUSAO
FROM AD_TMSCAL CAL
WHERE CAL.CODCAL = :CODCAL