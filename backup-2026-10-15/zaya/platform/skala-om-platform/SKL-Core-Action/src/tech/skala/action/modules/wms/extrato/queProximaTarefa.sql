SELECT 
	ITT.NUTAREFA,
	ITT.SEQUENCIA,
	ITT.CODPROD,
	ITT.CODENDORIGEM,
	EOR.DESCREND AS DESCRENDORIGEM,
	EOR.ENDERECO AS ENDERECOORIGEM,
	ITT.CODENDDESTINO,
	EDT.DESCREND AS DESCRENDDESTINO,
	EDT.ENDERECO AS ENDERECODESTINO,
	ITT.QTDORIG,
	ITT.CODVOLORIG,
	ITT.QTDDEST,
	ITT.CODVOLDEST,
	ITT.QTDVOLPAD,
	PRO.CODVOL AS CODVOLPAD,
	ITT.SITUACAO,
	ITT.CODUSUEXEC,
	ITT.DHINICIALEXEC,
	ITT.DHFINALEXEC,
	ITT.CODEMP,
	ITT.CODLOCAL,
	ITT.CONTROLE,
	ITT.TIPTAREFA,
	TAR.CODTAREFA,
	NULL AS NURECEBIMENTO,
	NULL AS NUNOTAREC,
	SEP.NUSEPARACAO,
	SEP.NUNOTA AS NUNOTASEP,
	SEP.ORDEMCARGA
FROM TGWITT ITT 
JOIN TGWTAR TAR ON (ITT.NUTAREFA = TAR.NUTAREFA)
LEFT OUTER JOIN TGWSEP SEP ON (ITT.NUTAREFA = SEP.NUTAREFA)
JOIN TGWEND EOR ON (ITT.CODENDORIGEM = EOR.CODEND)
JOIN TGWEND EDT ON (ITT.CODENDDESTINO = EDT.CODEND)
JOIN TGFPRO PRO ON (ITT.CODPROD = PRO.CODPROD)
WHERE
	(ITT.CODPROD = :CODPROD AND ITT.NUTAREFA > :NUTAREFAINICIAL AND ITT.CODENDORIGEM = :CODENDINICIAL)
ORDER BY ITT.NUTAREFA, ITT.SEQUENCIA