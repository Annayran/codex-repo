SELECT
    'E' ORIGEM,
    DEP.CODCENCUS,
    0 CODPROJ,
    (100/ :VLRNOTA ) * SUM(CMV.VLREMP) PERCRATEIO, 
    0 CODCTACTB,
    0 NUMCONTRATO,
    'S' DIGITADO,
    0 CODSITE
FROM TFPCBE CBE
    JOIN TFPCMV CMV ON (CBE.CODCBE = CMV.CODCBE)
    JOIN TFPFUN FUN ON (CMV.CODEMP = FUN.CODEMP AND CMV.CODFUNC = FUN.CODFUNC)
    JOIN TFPBEN BEN ON (CBE.CODBEN = BEN.CODBEN)
    JOIN TFPDEP DEP ON (FUN.CODDEP = DEP.CODDEP)
WHERE CBE.CODCBE = :CODCBE
GROUP BY BEN.CODBEN,BEN.DESCRICAO,CMV.CODEMP,CBE.REFERENCIA,DEP.CODCENCUS
