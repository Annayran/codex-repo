SELECT 
	METODO
FROM AD_PLTSIRNG RNG
WHERE RNG.TIPOEVENTO = :TIPOEVENTO
AND RNG.ATIVO = 'S'
AND (
	(RNG.TIPREST = 'T' AND EXISTS(SELECT 1 FROM AD_PLTSITRN TRN WHERE TRN.NURNG = RNG.NURNG AND TRN.CODTIPOPER = :CODTIPOPER AND TRN.RESTRICAO = 'E'))
	OR (RNG.TIPREST = 'C' AND EXISTS(SELECT 1 FROM AD_PLTSICRN CRN WHERE CRN.NURNG = RNG.NURNG AND CRN.TIPO = :TIPO AND CRN.RESTRICAO = 'E'))
)