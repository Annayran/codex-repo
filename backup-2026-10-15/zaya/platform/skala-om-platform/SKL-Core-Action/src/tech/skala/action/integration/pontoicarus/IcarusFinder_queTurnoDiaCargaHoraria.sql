SELECT 
this.DIASEM, this.DESCANSOSEM 
FROM TFPHOR /* CargaHoraria */ this
JOIN TFPCGH /* IdentificacaoCargaHoraria */ CGH ON (this.CODCARGAHOR = CGH.CODCARGAHOR)
JOIN TSIEMP /* Empresa */ EMP ON (EMP.CODEMP IN (1,2))
WHERE this.CODCARGAHOR = :CODCARGAHOR AND EMP.CODEMP = :CODEMP 
GROUP BY this.DIASEM, this.DESCANSOSEM
ORDER BY DIASEM, DESCANSOSEM