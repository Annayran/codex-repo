INSERT INTO DWTGFESTITE 
SELECT 
TRUNC(CAB.DTNEG) AS DTNEG, 
TRUNC(CAB.DTENTSAI) AS DTENTSAI, 
TRUNC(CASE WHEN ITE.ATUALESTOQUE = 1 THEN COALESCE(CAB.DTENTSAI,CAB.DTNEG) ELSE CAB.DTNEG END) AS DTREF, 
CAB.CODTIPOPER, 
CAB.DHTIPOPER, 
CAB.TIPMOV, 
ITE.NUNOTA, 
ITE.SEQUENCIA, 
ITE.CODEMP, ITE.CODPROD, ITE.CODLOCALORIG, ITE.CONTROLE, 0 AS CODPARC, 'P' AS TIPO, 
ITE.QTDNEG, ITE.QTDENTREGUE, ITE.QTDCONFERIDA, ITE.ATUALESTOQUE, ITE.ATUALESTINDIVIDUAL, ITE.ATUALESTTERC 
FROM DLTGFCAB CAB 
JOIN DLTGFITE ITE ON (CAB.NUNOTA = ITE.NUNOTA) 
WHERE 
ITE.ATUALESTOQUE != 0 AND ITE.RESERVA = 'N' 
AND TRUNC(CAB.DTNEG) BETWEEN TRUNC(SYSDATE)-30 AND TRUNC(SYSDATE)-1 
