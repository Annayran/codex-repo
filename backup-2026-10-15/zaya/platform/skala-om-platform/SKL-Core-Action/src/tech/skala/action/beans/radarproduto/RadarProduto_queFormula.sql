SELECT B.F2_MP CODPRODMP
     , SUM(B.QTDMISTURA) AS QTDMISTURA
     , B.CODVOLMP
     , B.CUS_MP
  FROM 
(
SELECT 
    V.F1_PA,
	V.F2_MP, 
	V.DESCRPRODMP, 
    V.QTDMISTURA,
    V.CODVOLMP,
    CASE WHEN V.GRUPOMATERIAL IN ('M', 'E') THEN V.CUSTOMP ELSE 0 END AS CUS_MP,
    V.IDPROC
FROM PLVPRBOM V
WHERE
	((V.PADRAO = 'S' AND V.USATERCEIRO = 'N') OR (V.USATERCEIRO = 'S'))
UNION ALL 
SELECT 
    V.F1_PA,
	V.F2_MP, 
	V.DESCRPRODMP, 
    V.QTDMISTURA,
    V.CODVOLMP,
    CASE WHEN V.GRUPOMATERIAL IN ('M', 'E') THEN V.CUSTOMP ELSE 0 END AS CUS_MP,
    V.IDPROC
FROM PLVPRBOMKIT V
WHERE
	((V.PADRAO = 'S' AND V.USATERCEIRO = 'N') OR (V.USATERCEIRO = 'S'))
	) B JOIN PLVPRPRCUV ON B.IDPROC = PLVPRPRCUV.IDPROC
WHERE
	(B.F1_PA = :CODPRODPA)
GROUP BY 
	B.F2_MP, 
	B.CODVOLMP, 
	B.CUS_MP