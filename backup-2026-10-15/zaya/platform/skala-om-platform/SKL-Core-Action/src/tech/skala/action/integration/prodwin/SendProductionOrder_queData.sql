SELECT
	OP.IDIPROC,
	OP.CODPRODPA,
	(
		SELECT
			T.DESCRPROD
		FROM
			TGFPRO T
		WHERE
			T.CODPROD = OP.CODPRODPA
	)AS DESCRPROD,
	1 CODWCP,
	IPA.QTDPRODUZIR,
	ROUND((IPA.QTDPRODUZIR * 60) / 30, 2) TAXAPRODUCAO,
	PRG.DTPROG AS DHINST,
	(PRG.DTPROG + 6 / 24) AS DHTERMINO,
	EMP.NOMEFANTASIA
FROM AD_PLTPRPRGPOP OP
JOIN AD_PLTPRPRGP PRG ON OP.NUPRGP = PRG.NUPRGP
JOIN TPRIPA IPA ON OP.IDIPROC = IPA.IDIPROC
JOIN TPRIPROC PROC ON OP.IDIPROC = PROC.IDIPROC
JOIN TPRPLP RLP ON PROC.CODPLP = RLP.CODPLP
JOIN TSIEMP EMP ON RLP.CODEMP = EMP.CODEMP
WHERE
	OP.IDIPROC = :IDIPROC
AND OP.NULOP = :NULOP
AND OP.NUPRGP = :NUPRGP
AND NOT EXISTS(
	SELECT
		1
	FROM
		AD_PLTPRPRGPOPPRODWIN PRODWIN
	WHERE
			PRODWIN.IDIPROC = OP.IDIPROC
		AND PRODWIN.NULOP = OP.NULOP
		AND PRODWIN.NUPRGP = OP.NUPRGP
)