SELECT 
	CAB.CODEMP,
	CAB.TIPMOV, 
	CAB.STATUSNOTA,
	CAB.DTNEG, 
	CAB.NUNOTA,
	CN.CODCAL,
	OCO.CODOCO
FROM DLTGFCAB CAB 
JOIN AD_TMSCALNOTA CN ON (CN.NUNOTA = CAB.NUNOTA)
JOIN AD_TMSCALOCO OCO ON (CN.CODCAL = OCO.CODCAL)
WHERE
	CAB.CODEMP IN (2) 
AND CAB.STATUSNOTA = 'L'
AND CAB.TIPMOV IN ('V','D') 
AND NOT EXISTS(SELECT 1 FROM AD_PLTGFENT T WHERE T.NUNOTA = CAB.NUNOTA)
AND NOT EXISTS(SELECT 1 FROM AD_PLTGFENTOCO T WHERE T.NUNOTA = CAB.NUNOTA AND T.CODOCO = OCO.CODOCO AND T.DHOCORRENCIA = OCO.DHOCORRENCIA)
AND ROWNUM < 200