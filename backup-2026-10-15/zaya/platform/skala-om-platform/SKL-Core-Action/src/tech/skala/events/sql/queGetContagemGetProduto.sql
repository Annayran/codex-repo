WITH C AS
(
	SELECT 
		TRUNC(CTE.DTCONTAGEM) AS DTCONTAGEM, 
		CTE.CODEMP,
		CTE.CODLOCAL,
		CTE.CODPROD, 
		SUM(CTE.QTDEST) AS ESTOQUE
	FROM TGFCTE CTE 
	WHERE
         CTE.CODLOCAL NOT IN (500000)
         AND CTE.SEQUENCIA = (
				SELECT MAX(T.SEQUENCIA) 
				FROM TGFCTE T 
				WHERE 
					T.CODEMP = CTE.CODEMP 
				AND T.CODPROD = CTE.CODPROD 
				AND T.CODLOCAL = CTE.CODLOCAL 
				AND T.CODPARC = CTE.CODPARC  
				AND T.CONTROLE = CTE.CONTROLE 
				AND T.DTCONTAGEM = CTE.DTCONTAGEM 
				AND T.SEQUENCIA > 1)
	AND (CTE.CODPROD = :P_CODPROD)
	GROUP BY
		CTE.DTCONTAGEM, 
		CTE.CODEMP,
		CTE.CODLOCAL,
		CTE.CODPROD
    ORDER BY CTE.DTCONTAGEM DESC
)
SELECT 
    C.DTCONTAGEM,
    C.CODPROD,
	COALESCE(SUM(C.ESTOQUE), 0) AS QTDCONTAGEM
FROM C
WHERE
    (C.DTCONTAGEM <= :P_DTPROG)
    AND ROWNUM = 1
GROUP BY
    C.DTCONTAGEM,
    C.CODPROD