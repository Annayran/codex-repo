  SELECT ITE.NUNICO
       , ITE.CODPROD
       , ITE.CONTROLE
       , PRO.CODVOL
       , SUM(ITE.QTDEST) QTDEST
       , QTDEVOLPADRAO(ITE.CODPROD, SUM(ITE.QTDEST) ,PRO.CODVOL) QTDESTUNCAD
       , ITE.DTFABRICACAO
       , ITE.DTVAL
       , ITE.CODLOCAL
       , ITE.CODPARC
       , ITE.CODEMP
    FROM AD_PLTTGFCTETERITE ITE LEFT JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
   WHERE ITE.NUNICO = :NUNICO
     AND ITE.DTCONTAGEM = :DTCONTAGEM
GROUP BY ITE.NUNICO
       , ITE.CODPROD
       , ITE.CONTROLE
       , PRO.CODVOL
       , ITE.DTFABRICACAO
       , ITE.DTVAL
       , ITE.CODLOCAL
       , ITE.CODPARC
       , ITE.CODEMP