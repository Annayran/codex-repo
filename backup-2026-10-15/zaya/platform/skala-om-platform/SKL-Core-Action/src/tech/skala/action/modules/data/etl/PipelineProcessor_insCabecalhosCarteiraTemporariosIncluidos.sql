INSERT INTO DWTGFCABCART_TMP_INC
SELECT NUNOTA
FROM DLTGFCAB CAB 
WHERE 
	(CAB.TIPMOV = 'P' AND CAB.CODEMP = 2)
AND EXISTS (SELECT 1 FROM AD_TPLTTOPCART T WHERE T.CODTIPOPER = CAB.CODTIPOPER AND T.TIPO IN ('P','PE','E','EB','EE','R','RB','RE','B'))
AND EXISTS (SELECT 1 FROM DLTGFITE ITE WHERE ITE.NUNOTA = CAB.NUNOTA AND ITE.PENDENTE = 'S' AND ITE.RESERVA = 'N')