SELECT
 ITE.CODPROD,
 ITE.QTDAPROVADA AS QTDSOLIC,
 ITE.VLRUNIT,
 ITE.QTDSOLIC*ITE.VLRUNIT AS VLRTOT,
 ITE.CODVOL,
 ITE.DTPREVENT,
 PRO.USOPROD,
CASE WHEN NVL(PRO.USALOCAL,'N')='S' THEN 
(SELECT INTEIRO FROM TSIPAR WHERE CHAVE='LOCALPADRAO' AND  CODUSU = 
(SELECT NUMINT FROM TWFIVAR WHERE NOME = 'CODUSUCOMPRAS' AND IDINSTPRN =CAB.IDINSTPRN)) ELSE 0 END AS LOCALPAD
FROM AD_PLTFLCABCOMPRAS CAB
JOIN AD_PLTFLITEMAPROVADOS ITE ON CAB.IDINSTPRN = ITE.IDINSTPRN
JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
WHERE CAB.IDINSTPRN = :IDINSTPRN
AND ITE.APROGESTOR = 'SIM'
AND ITE.CODPARC = :CODPARC