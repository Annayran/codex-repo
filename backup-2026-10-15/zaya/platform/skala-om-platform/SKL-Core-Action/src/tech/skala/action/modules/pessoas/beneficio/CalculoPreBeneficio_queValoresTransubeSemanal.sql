WITH RAD AS (
  SELECT F.CODEMP,F.CODFUNC,F.NOMEFUNC, decode(F.SITUACAO,0,'DEMITIDO'
    ,1,'ATIVO'       ,2,'AFASTADO SR'     ,3,'AFASTADO AT'
    ,4,'AFASTADO SM' ,5,'MATERNIDADE'     ,6,'AFASTADO AC 15 d/d'
    ,7,'OUTROS'      ,8,'TRANSFERIDO'     ,9,'APOSENTADO' ) as SITUACAO,F.DTADM,
    F.DTDEM,F.CODDEP,DEP.DESCRDEP,--F.CODFUNCAO,FCO.DESCRFUNCAO,--F.CODCARGAHOR,
    TFPHOR.CODCARGAHOR,
    TFPHOR.DESCRCARGAHOR,
    TFPLIM.TURNO,
    TFPLIM.ENTRADA,
    TFPLIM.SAIDA,
    F.AD_TURNO,
    F.DISPENSAPONTO,
    DECODE(FBE.CODBEN,'','20',FBE.CODBEN) CODBEN,
    BEN.DESCRICAO DESCRBEN,
    DECODE(FBE.CODBEN,'','FUNCIONARIO NAO ESTA RELACIONADO NO BEN-20','') OBSERVACAO,
    FBE.AD_PASSES AS INDBEN,
    (FBE.AD_PASSES *BEN.VLRPARTEEMPRESA)  AS VLRBEN,
    
    (select COUNT(BT.HORA) BATIDAS FROM TFPAFDT BT
        where BT.CODEMP = F.CODEMP AND BT.CODFUNC = F.CODFUNC AND 
             BT.DTMOV = :DTPON  AND BT.TIPREGISTRO = 'O' )  as Batidas,
    
    (select TO_CHAR(NVL(MIN(BT.HORA),0),'99,00') BATIDAS from TFPAFDT BT
        where BT.CODEMP = F.CODEMP AND BT.CODFUNC = F.CODFUNC AND 
             BT.DTMOV = :DTPON AND BT.TIPREGISTRO = 'O' ) as MINBatida,
    
    TRUNC(:DTPON) PERIODO ,
    (SELECT  ( (trunc(FE.DTFINALOCOR) - trunc(:DTPON) +1)) FROM TFPOCO FE
        WHERE FE.CODHISTOCOR = 10 AND :DTPON between trunc(FE.DTINICOCOR) AND 
           trunc(FE.DTFINALOCOR) and FE.CODEMP = F.CODEMP AND FE.CODFUNC = F.CODFUNC  ) DIASCASAMENTOREST,       -- CASAMENTO
    (SELECT  ( (trunc(FE.DTFINALOCOR) - trunc(:DTPON) +1)) FROM TFPOCO FE
        WHERE FE.CODHISTOCOR = 11 AND :DTPON between trunc(FE.DTINICOCOR) AND 
           trunc(FE.DTFINALOCOR) and FE.CODEMP = F.CODEMP AND FE.CODFUNC = F.CODFUNC  ) DIASPATERNIDADEREST,     -- PATERNIDADE
    (SELECT  ( (trunc(FE.DTFINALOCOR) - trunc(:DTPON) +1)) FROM TFPOCO FE
        WHERE FE.CODHISTOCOR = 12 AND :DTPON between trunc(FE.DTINICOCOR) AND 
           trunc(FE.DTFINALOCOR) and FE.CODEMP = F.CODEMP AND FE.CODFUNC = F.CODFUNC  ) DIASOBITOREST,     -- OBITO
    (SELECT  ( (trunc(FE.DTFINALOCOR) - trunc(:DTPON) +1)) FROM TFPOCO FE
        WHERE FE.CODHISTOCOR = 27 AND :DTPON between trunc(FE.DTINICOCOR) AND 
           trunc(FE.DTFINALOCOR) and FE.CODEMP = F.CODEMP AND FE.CODFUNC = F.CODFUNC  ) DIASFERIASREST,       -- FERIAS
    (SELECT  max(( (trunc(AF.DTFINALOCOR) - trunc( :DTPON) +1))) FROM TFPOCO AF
       WHERE AF.CODHISTOCOR = 18 AND :DTPON between trunc(AF.DTINICOCOR) AND 
           trunc(AF.DTFINALOCOR) and AF.CODEMP = F.CODEMP AND AF.CODFUNC = F.CODFUNC  ) DIASATESTADOMEDICOREST,     -- ATESTADO 
    CASE 
      LENGTH(DECODE(TRIM(REPLACE(AD_CARTAOVT,'.','')),'','NAO',TRIM(REPLACE(AD_CARTAOVT,'.',''))))
       WHEN 10  THEN 'SIM'
       WHEN 9  THEN 'SIM'
       WHEN 8  THEN 'SIM'
       WHEN 7  THEN 'SIM'
       ELSE 'NAO'
    END AS VALETRANSP,
    F.AD_CARTAOVT CARTAOVT,
    F.AD_CARTAOVT CARTAONOBEN --FBE.AD_CARTAO

    FROM TFPFUN F
      INNER JOIN TFPDEP DEP ON F.CODDEP = DEP.CODDEP
      INNER JOIN TFPFCO FCO ON F.CODFUNCAO = FCO.CODFUNCAO
      INNER JOIN (SELECT -- TFPHOR
      HOR1.CODEMP , HOR1.CODFUNC , HOR1.CODCARGAHOR , CGH.DESCRCARGAHOR
      FROM (
        SELECT  CODEMP  , CODFUNC , CODCARGAHOR , MAX(DHALTER) DHALTER
       FROM (SELECT FHO.CODEMP , FHO.CODFUNC  , FHO.CODCARGAHOR , DHALTER
            FROM TFPFHO FHO WHERE FHO.DHALTER =(SELECT MAX( (TO_DATE(DHALTER))) FROM TFPFHO HIS 
                  WHERE HIS.CODFUNC = FHO.CODFUNC AND HIS.CODEMP = FHO.CODEMP)
              ) GROUP BY CODEMP, CODFUNC , CODCARGAHOR
          ) HOR1
       INNER JOIN TFPCGH CGH ON (CGH.CODCARGAHOR = HOR1.CODCARGAHOR )
       ) TFPHOR ON (TFPHOR.CODEMP    = F.CODEMP AND  TFPHOR.CODFUNC   = F.CODFUNC) 
     INNER JOIN (SELECT  HOR.CODCARGAHOR,  HOR.DIASEM,  HOR.DESCANSOSEM,  HOR.TURNO,  HOR.ENTRADA,  HOR.SAIDA,
                  SUM(CASE WHEN NVL(HOR.SAIDA, 0)< NVL(HOR.ENTRADA, 0) THEN 1440 ELSE 0 END + 
                  ((FLOOR(NVL(HOR.SAIDA, 0)/100) * 60) + (NVL(HOR.SAIDA, 0) - FLOOR(NVL(HOR.SAIDA, 0) / 100) * 100)) -
                  ((FLOOR(NVL(HOR.ENTRADA, 0)/100) * 60) + (NVL(HOR.ENTRADA, 0) - FLOOR(NVL(HOR.ENTRADA, 0) / 100) * 100))) AS CARGAHOR
                FROM TFPHOR HOR
            WHERE HOR.DIASEM =  to_char(:DTPON,'d')  
                AND  HOR.TURNO = 1
            GROUP BY  HOR.CODCARGAHOR,HOR.DIASEM,HOR.DESCANSOSEM,
              HOR.TURNO, HOR.ENTRADA,  HOR.SAIDA
       ) TFPLIM ON (TFPHOR.CODCARGAHOR  = TFPLIM.CODCARGAHOR)
       left JOIN TFPFBE FBE ON (FBE.CODEMP = F.CODEMP AND FBE.CODFUNC = F.CODFUNC AND FBE.CODBEN In (20))
       left JOIN TFPBEN BEN ON (FBE.CODBEN = BEN.CODBEN)
WHERE F.CODEMP in 1 AND
  NVL(F.DISPENSAPONTO,'S') IN 'N' AND F.SITUACAO NOT IN (0,8) AND F.VINCULO NOT IN (90) 
) 
 SELECT 
    RAD.CODEMP,
    RAD.CODFUNC,
    RAD.NOMEFUNC, 
    :DTPON AS DTREF,
    TO_CHAR(:DTREF,'DD') AS DIAREF,
	TO_CHAR(:DTREF,'MM') AS MESREF,
	TO_CHAR(:DTREF,'YYYY') AS ANOREF,
    RAD.CODBEN,
    DECODE(RAD.VLRBEN,'',0, (RAD.VLRBEN) ) VLRBEN,
    DECODE(RAD.VLRBEN,'',0,RAD.INDBEN) QTDIASTRAB,
    0 DIASFALTAS,
    0 ATESTDIAS,
    DECODE(RAD.VLRBEN,'',0,RAD.INDBEN) INDBEN,
    OBSERVACAO,
	RAD.CODCARGAHOR,
    RAD.DESCRCARGAHOR,
    0 VLRCRE,
    0 VLRDEB,
    0 INDCRE,
    0 INDDEB,
    0 FALTAS,
    0 ATESTADOS,
    RAD.SITUACAO,
    RAD.DTADM,
    RAD.DTDEM,
    RAD.DESCRBEN,
    :DTREF AS DTPON,
    RAD.CARTAOVT,
    RAD.CARTAONOBEN
FROM RAD
WHERE VALETRANSP = 'SIM'
    AND BATIDAS not IN (0,1)
    AND CODCARGAHOR IN(1,16,23,101,137,170)
    AND DIASFERIASREST IS NULL
    AND DIASATESTADOMEDICOREST IS NULL
    AND DIASCASAMENTOREST IS NULL
    AND DIASPATERNIDADEREST IS NULL
    AND DIASOBITOREST IS NULL
    AND RAD.CARTAONOBEN IS NOT NULL
    --ORDER BY RAD.NOMEFUNC
UNION ALL
SELECT 
    FBE.CODEMP,
    FBE.CODFUNC,
    FUN.NOMEFUNC,
    :DTPON AS DTREF,
    TO_CHAR(:DTREF,'DD') AS DIAREF,
    TO_CHAR(:DTREF,'MM') AS MESREF,
	TO_CHAR(:DTREF,'YYYY') AS ANOREF,
    '20' CODBEN,
    8.50 VLRBEN,
    2 QTDIASTRAB,
    0 DIASFALTAS,
    0 ATESTDIAS,
    2 INDBEN,
    'CAD.FUNCIONARIO RELACIONAMENTO BENEFICIO-20' OBSERVACAO,
    0 CODCARGAHOR, 
    'CARGA HORARIA PADRAO' DESCRCARGAHOR,
    0 VLRCRE,
    0 VLRDEB,
    0 INDCRE,
    0 INDDEB,
    0 FALTAS,
    0 ATESTADOS,
    decode(FUN.SITUACAO,0,'DEMITIDO'
    ,1,'ATIVO'       ,2,'AFASTADO SR'     ,3,'AFASTADO AT'
    ,4,'AFASTADO SM' ,5,'MATERNIDADE'     ,6,'AFASTADO AC 15 d/d'
    ,7,'OUTROS'      ,8,'TRANSFERIDO'     ,9,'APOSENTADO' ) as SITUACAO,
    FUN.DTADM,
    FUN.DTDEM,
    'BENEFICIO 20' DESCRBEN,
    :DTREF AS DTPON,
	FUN.AD_CARTAOVT CARTAOVT,
    FUN.AD_CARTAOVT CARTAONOBEN
FROM TFPFBE FBE,TFPFUN FUN
WHERE FBE.CODEMP = FUN.CODEMP AND FBE.CODFUNC = FUN.CODFUNC
    AND CODBEN = 20
    AND AD_CARTAO IS NULL
ORDER BY 3