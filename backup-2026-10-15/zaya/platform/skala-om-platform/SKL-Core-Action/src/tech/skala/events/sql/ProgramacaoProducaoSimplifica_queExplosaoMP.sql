SELECT X.F2_MP, 
    X.DESCRPRODMP,
    X.CODVOLMP,
    SUM(X.QTDMISTURA) QTDMISTURA,
    COALESCE(PRO.LEADTIME, 7) LEADTIME,
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN LMP.CODLOCALORIG ELSE PROEST.CODLOCALBAIXAMP END CODLOCAL,
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN LOC.DESCRLOCAL ELSE PROESTLOC.DESCRLOCAL END DESCRLOCAL,
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN COALESCE(EST.CODEMP, 1) ELSE COALESCE(ESTPROEST.CODEMP, 1) END CODEMP,
    SUM(CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN (COALESCE(EST.ESTOQUE, 0) - COALESCE(EST.RESERVADO, 0)) ELSE (COALESCE(ESTPROEST.ESTOQUE, 0) - COALESCE(ESTPROEST.RESERVADO, 0)) END) ESTOQUE,
    0 QTDPENDENTE
  FROM (
SELECT 
    B.F2_MP, 
    B.DESCRPRODMP,
    B.CODVOLMP,
    B.QTDMISTURA,
    B.F1_PA,
    B.CODPRC
FROM PLVPRBOM B 
WHERE
    (B.CODPRC = :CODPRC AND B.F1_PA = :CODPRODPA)
UNION ALL
SELECT 
    B.F2_MP, 
    B.DESCRPRODMP,
    B.CODVOLMP,
    B.QTDMISTURA,
    B.F1_PA,
    B.CODPRC
FROM PLVPRBOMKIT B 
WHERE
    (B.CODPRC = :CODPRC AND B.F1_PA = :CODPRODPA)
) X INNER JOIN TGFPRO PRO ON(X.F2_MP = PRO.CODPROD)                                                                                 /* Mat�ria Prima da vis�o padr�o x Produto */
    INNER JOIN TPRLMP LMP ON(X.F1_PA = LMP.CODPRODPA AND X.F2_MP = LMP.CODPRODMP)                                                   /* Lista de Mat�ria Prima */
    INNER JOIN TPREFX EFX ON(EFX.IDEFX = LMP.IDEFX)                                                                                 /* Processo Produtivo */
    INNER JOIN TGFLOC LOC ON(LOC.CODLOCAL = LMP.CODLOCALORIG)                                                                       /* Local da Lista de Mat�ria Prima */
    INNER JOIN TPROEST PROEST ON(EFX.IDEFX = PROEST.IDEFX)                                                                          /* Opera��o de Estoque do Processo Produtivo */
    INNER JOIN TGFLOC PROESTLOC ON (PROEST.CODLOCALBAIXAMP = PROESTLOC.CODLOCAL)                                                    /* Local da Opera��o de Estoque do Processo Produtivo */
    LEFT JOIN TGFEST EST ON(X.F2_MP = EST.CODPROD AND LOC.CODLOCAL = EST.CODLOCAL AND EST.TIPO = 'P')                               /* Estoque do Local da Lista de Mat�ria Prima */
    LEFT JOIN TGFEST ESTPROEST ON(X.F2_MP = ESTPROEST.CODPROD AND PROESTLOC.CODLOCAL = ESTPROEST.CODLOCAL AND ESTPROEST.TIPO = 'P') /* Estoque do Local da Opera��o de Estoque do Processo Produtivo */
WHERE (EFX.IDPROC IN (SELECT IDPROC FROM AD_PLVPRPRC WHERE CODPRC = X.CODPRC))
GROUP BY X.F2_MP, 
    X.DESCRPRODMP,
    X.CODVOLMP,
    --X.QTDMISTURA,
    COALESCE(PRO.LEADTIME, 7),
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN LMP.CODLOCALORIG ELSE PROEST.CODLOCALBAIXAMP END,
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN LOC.DESCRLOCAL ELSE PROESTLOC.DESCRLOCAL END,
    CASE WHEN COALESCE(LMP.CODLOCALORIG, 0) != 0 THEN COALESCE(EST.CODEMP, 1) ELSE COALESCE(ESTPROEST.CODEMP, 1) END
ORDER BY X.F2_MP