WITH PERIODO AS 
(
SELECT 
	EMP.CODEMP,
	this.*
FROM TFPHOR /* CargaHoraria */ this
JOIN TSIEMP /* Empresa */ EMP ON EMP.CODEMP IN (1,2)
WHERE
	(this.ENTRADA IS NOT NULL)
AND (this.CODCARGAHOR = :CODCARGAHOR AND this.DIASEM = :DIASEM)
AND (EMP.CODEMP = :CODEMP) 
ORDER BY CODCARGAHOR, DIASEM, TURNO
)
SELECT 
	CODEMP,
	DIASEM,
	TURNO,
	ENTRADA AS HORAENTSAI,
	TO_CHAR(TO_DATE(TO_CHAR(ENTRADA, '0000'),'HH24MI'),'HH24:MI') AS HORATURNO,
	'ENTRADA' AS TIPO
FROM PERIODO
UNION ALL
SELECT 
	CODEMP,
	DIASEM,
	TURNO,
	SAIDA AS HORAENTSAI,
	TO_CHAR(TO_DATE(TO_CHAR(SAIDA, '0000'),'HH24MI'),'HH24:MI') AS HORATURNO,
	'SAIDA' AS TIPO
FROM PERIODO
ORDER BY DIASEM, TURNO, TIPO