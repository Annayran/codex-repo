SELECT 
	ORD.CODEMP,
	ORD.ORDEMCARGA,
	CAB.NUNOTA,
	CAB.CODTIPOPER,
	CAB.TIPMOV,
	CAB.NUMNOTA,
	CAB.DTNEG,
	CAB.DTFATUR,
	CAB.CODPARC,
	ITE.CODPROD,
	ITE.QTDNEG,
	QTDEVOLPADRAO(ITE.CODPROD,ITE.QTDNEG,ITE.CODVOL) AS QTDNEGCX,
	ITE.CODVOL,
	PAR.CODPARC,
	PAR.NOMEPARC,
	PAR.RAZAOSOCIAL,
	PAR.CGC_CPF AS CNPJ
FROM TGFORD ORD 
JOIN TGFCAB CAB ON (CAB.CODEMP = ORD.CODEMP AND CAB.ORDEMCARGA = ORD.ORDEMCARGA) 
JOIN TGFITE ITE ON (CAB.NUNOTA = ITE.NUNOTA)
JOIN TGFPAR PAR ON (CAB.CODPARC = PAR.CODPARC)
WHERE
	(ORD.CODEMP = :CODEMP AND ORD.ORDEMCARGA = :ORDEMCARGA)
AND (CAB.TIPMOV = 'V')
AND (ITE.CODPROD = :CODPROD)