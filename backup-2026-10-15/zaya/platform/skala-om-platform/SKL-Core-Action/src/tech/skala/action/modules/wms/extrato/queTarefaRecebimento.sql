SELECT 
	(SELECT T.NUMNOTA FROM TGFCAB T WHERE T.NUNOTA = REC.NUNOTA) AS NUMNOTAREC,
	ITT.NUTAREFA,
	ITT.SEQUENCIA,
	ITT.CODPROD,
	ITT.CODENDORIGEM,
	EOR.DESCREND AS DESCRENDORIGEM,
	EOR.ENDERECO AS ENDERECOORIGEM,
	ITT.CODENDDESTINO,
	EDT.DESCREND AS DESCRENDDESTINO,
	EDT.ENDERECO AS ENDERECODESTINO,
	ITT.QTDORIG,
	ITT.CODVOLORIG,
	ITT.QTDDEST,
	ITT.CODVOLDEST,
	ITT.QTDVOLPAD,
	PRO.CODVOL AS CODVOLPAD,
	ITT.SITUACAO,
	ITT.CODUSUEXEC,
	ITT.DHINICIALEXEC,
	ITT.DHFINALEXEC,
	ITT.CODEMP,
	ITT.CODLOCAL,
	ITT.CONTROLE,
	ITT.TIPTAREFA,
	TAR.CODTAREFA,
	REC.NURECEBIMENTO,
	REC.NUNOTA AS NUNOTAREC,
	NULL AS NUSEPARACAO,
	NULL AS NUNOTASEP,
	NULL AS ORDEMCARGA
FROM TGWITT ITT 
JOIN TGWTAR TAR ON (ITT.NUTAREFA = TAR.NUTAREFA)
JOIN TGWREC REC ON (ITT.NUTAREFA = REC.NUTAREFA)
JOIN TGWEND EOR ON (ITT.CODENDORIGEM = EOR.CODEND)
JOIN TGWEND EDT ON (ITT.CODENDDESTINO = EDT.CODEND)
JOIN TGFPRO PRO ON (ITT.CODPROD = PRO.CODPROD)
WHERE
	(ITT.CODPROD = :CODPROD AND REC.NUNOTA = :NUNOTA)