SELECT 
	this.NUOCOR,
	this.CODEMP,
	this.CODFUNC,
	this.CODHISTOCOR,
	this.DTINICOCOR,
	this.DTFINALOCOR,
	this.DESCROCOR
FROM TFPOCO /* RegistroOcorrencia */ this 
WHERE 
	this.CODHISTOCOR IN (27) 
AND this.DTINICOCOR > TO_DATE('19/05/2023','DD/MM/YYYY') 
AND NOT EXISTS(SELECT 1 FROM AD_PLTPIOCO T WHERE T.NUOCOR = this.NUOCOR) 
AND EXISTS(SELECT 1 FROM AD_PLTPICFGEMP T WHERE T.CODEMP = :CODEMP AND T.CODEMPGRP = this.CODEMP) 
AND this.CODFUNC = 682 
