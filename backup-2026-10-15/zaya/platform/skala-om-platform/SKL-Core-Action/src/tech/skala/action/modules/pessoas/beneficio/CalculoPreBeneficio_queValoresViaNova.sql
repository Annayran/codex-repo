SELECT
	CODEMP,
	CODFUNC,
	NOMEFUNC,
	DTADM,
	DTDEM,
	DTTRANSF,
	VINCULO,
	CODBEN,
	DESCRICAO,
    CODCARGAHOR,
    DESCRCARGAHOR,
	VLRPARTEEMPRESA VLREMP,
	FTMULTIPLICA,
	((DTAPFIM - DTAPINI)+ 1) DIASTRABMES,
	DTREF,
	DTAPINI,
	DTAPFIM,
	DIASFALTAS,
	ATESTDIAS,
	PERATRASOS,
	OCORNAOABONADAS,
	QTDDIAS,
	DIASTRABDEM,
	DIASAVISO,
	TIPAVISO,
	TIPAVISOBAS,
	FERIAS,
	AFASTAMENTO AFASTAMENTOMES,
	SITUACAO,
	DIAREF,
	ANOREF,
	MESREF,
	IDADM,
	IDDEM,
	QTDIASTRAB,
	QTDIASTRABPROP,
	QTDIASAFAST AFASTAMENTOPONTO,
	IDMARCADOR,
	CODTPR,
	(QTDIASTRAB -(ATESTDIAS + NVL(DIASFALTAS,0))) INDBEN,
	(((QTDIASTRAB -(ATESTDIAS + NVL(DIASFALTAS,0)))* FTMULTIPLICA)) VLRBEN,
    '' OBSERVACAO	
FROM (
	SELECT
		FBE.CODEMP,
		FBE.CODFUNC,
		FUN.NOMEFUNC,
		FUN.VINCULO,
		FUN.DTDEM,
		FUN.DTTRANSFERENCIA,
		FBE.AD_VLRINTER,
		FBE.AD_VLRMUNICIPAL,
		COALESCE(FBE.AD_VLRINTER,FBE.AD_VLRMUNICIPAL) AS FTMULTIPLICA,
	    TRA.CODCARGAHOR,
    	TRA.DESCRCARGAHOR,
		FBE.CODBEN,
		BEN.DESCRICAO,
		BEN.VLRPARTEEMPRESA,
		FUN.DTTRANSFERENCIA DTTRANSF,
		TO_DATE('01/'||SUBSTR(TRA.ANOMES,5,2)||'/'||SUBSTR(TRA.ANOMES,1,4)) DTREF,
		TO_DATE('20/'|| TO_CHAR(ADD_MONTHS( TO_DATE('01/'||SUBSTR(TRA.ANOMES,5,2)||'/'||SUBSTR(TRA.ANOMES,1,4)), - 1), 'MM/YYYY')) DTAPINI,
		TO_DATE('19/'||SUBSTR(TRA.ANOMES,5,2)||'/'||SUBSTR(TRA.ANOMES,1,4)) DTAPFIM,
		NVL(OCI.DOENCA15DIAS,0) AFASTAMENTO,
		NVL(OCI.DIASFALTAS,0) DIASFALTAS,
		NVL(OCI.ATESTDIAS,0) ATESTDIAS,
		NVL(OCI.PERATRASOS,0) PERATRASOS,
		NVL(OCI.OCORNAOABONADAS,0) OCORNAOABONADAS,
		(NVL(OCI.DIASFALTAS,0)+NVL(OCI.ATESTDIAS,0)+NVL(OCI.PERATRASOS,0)+NVL(OCI.OCORNAOABONADAS,0)) QTDDIAS, -- PERDA DO VALOR NO MES
		TRA.DTADM,
		TRA.IDADM,
		TRA.IDDEM,
		FUN.SITUACAO,
		DECODE(FUN.SITUACAO,6,1,0) IDAFA,
		NVL(DEM.CODTPR,0) CODTPR,
		DECODE((NVL(OCI.DIASFALTAS,0)+
			NVL(OCI.ATESTDIAS,0)+
			NVL(OCI.PERATRASOS,0)+
			NVL(OCI.OCORNAOABONADAS,0)),0,'0','1')||TO_CHAR(IDADM)||TO_CHAR(IDDEM)||DECODE(FUN.SITUACAO,6,1,0) IDMARCADOR,
		TRA.QTDIASTRAB QTDIASTRAB,
		DECODE(TRA.IDADM,1,
		COALESCE( TO_DATE('19'||'/'||SUBSTR(TRA.ANOMES,5,2)||'/'||SUBSTR(TRA.ANOMES,1,4) ) - TO_DATE(TRA.DTADM) + 1,0),0) QTDIASTRABPROP,
		CASE WHEN NVL(OCI.DOENCA15DIAS,0)  - tra.QTDIASTRAB < 0 THEN 0 ELSE 0 END AS QTDIASAFAST,      
		NVL(OCI.FERIAS,0) FERIAS,
		SUBSTR(:DTREF,1,2) DIAREF,
		SUBSTR(TRA.ANOMES,1,4) ANOREF,
		SUBSTR(TRA.ANOMES,5,2) MESREF,
		TIPAVISO AS TIPAVISOBAS,
		DECODE(NVL(DEM.TIPAVISO,0),0,0, 
				   1,0,
				   2,NVL(DEM.DIASAVISO,0),
				   3,NVL(DEM.DIASAVISO,0)) AS DIASAVISO,
		NVL(DEM.DIASTRABDEM,0) DIASTRABDEM,
		NVL(DEM.TIPAVISO,0) TIPAVISO
	FROM TFPFBE FBE 
	JOIN TFPFUN FUN ON (FBE.CODEMP = FUN.CODEMP AND FBE.CODFUNC = FUN.CODFUNC)
	JOIN TFPBEN BEN ON ( FBE.CODBEN = BEN.CODBEN)
	JOIN PLVTDIASTRABALHADOS TRA ON (FBE.CODEMP = TRA.CODEMP AND TRA.CODFUNC = FUN.CODFUNC)
	LEFT JOIN AD_VTBENEFICIOSOCOR OCI ON (FBE.CODEMP = OCI.CODEMP AND TRA.CODFUNC = OCI.CODFUNC and  OCI.ANOREF||OCI.MESREF = TO_CHAR(:DTPON, 'YYYYMM'))
	LEFT JOIN PLVDIASTRABDEMISSAO DEM ON (FBE.CODEMP = DEM.CODEMP AND TRA.CODFUNC = DEM.CODFUNC and  TO_CHAR(TO_DATE(DEM.DTREF),'YYYYMM') = TO_CHAR(:DTPON, 'YYYYMM')) -- JAVA NAO PRECISA TO_DATE
	WHERE 
		FUN.VINCULO NOT IN ( 30, 80, 90, 99)
	AND TRA.ANOMES = TO_CHAR(:DTREF, 'YYYYMM')
	AND BEN.CODBEN IN (17)
)