SELECT 
	this.CODEMP, 
	this.CODFUNC, 
	FUN.IDMUTUARIO, 
	this.DTINICOCOR, 
	TO_CHAR(this.DTINICOCOR, 'DD/MM/YYYY HH:mi') AS DTINICOCORSTR 
FROM TFPOCO this 
JOIN AD_PLTPIFUN FUN ON (FUN.CODEMP = this.CODEMP AND FUN.CODFUNC = this.CODFUNC) 
WHERE 
this.DTINICOCOR > TO_DATE('19/05/2023','DD/MM/YYYY') 
AND EXISTS(SELECT 1 FROM AD_PLTPIHIS T WHERE T.CODEMP = :CODEMPREF AND T.CODHISTOCOR = this.CODHISTOCOR) 
AND EXISTS(SELECT 1 FROM AD_PLTPICFGHIS T WHERE T.CODHISTOCOR =  this.CODHISTOCOR AND T.TIPO IN ('O')) 
AND EXISTS(SELECT 1 FROM AD_PLTPICFGEMP T WHERE T.CODEMP = :CODEMPREF AND T.CODEMPGRP = this.CODEMP) 
AND NOT EXISTS(SELECT 1 FROM AD_PLTPIOCO T WHERE T.NUOCOR = this.NUOCOR) 
GROUP BY
	this.CODEMP, 
	this.CODFUNC, 
	FUN.IDMUTUARIO, 
	this.DTINICOCOR
ORDER BY
	this.CODEMP,
	this.CODFUNC,
	this.DTINICOCOR
