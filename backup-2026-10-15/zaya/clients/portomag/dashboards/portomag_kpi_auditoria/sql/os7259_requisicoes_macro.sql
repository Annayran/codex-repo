/* OS 7259 / Item 13 - KPI macro auditavel.
   Usa a mesma base do detalhamento, portanto os totais conferem linha a linha.
*/
WITH BASE AS (
    SELECT *
    FROM (
        /* Substituir este bloco pela query os7259_requisicoes_detalhe.sql
           quando o componente Sankhya nao aceitar CTE compartilhada por arquivo. */
        WITH PARAMS AS (
            SELECT TRUNC(:PERIODO.INI) DTINI, TRUNC(:PERIODO.FIN) DTFIN, NVL(:DIASPRAZO, 7) DIASPRAZO FROM DUAL
        ),
        REQ_ITEM AS (
            SELECT CAB.NUNOTA, ITE.SEQUENCIA, CAB.CODTIPOPER, TOP.DESCROPER, ITE.CODPROD, PRO.DESCRPROD,
                   TRUNC(CAB.DTNEG) DT_REQUISICAO, TRUNC(NVL(CAB.DTENTSAI, CAB.DTNEG)) DT_INICIO_CALCULO
            FROM TGFCAB CAB
            INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
            INNER JOIN TGFTOP TOP ON TOP.CODTIPOPER = CAB.CODTIPOPER AND TOP.DHALTER = CAB.DHTIPOPER
            INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
            CROSS JOIN PARAMS P
            WHERE CAB.CODTIPOPER IN (400, 401)
              AND TRUNC(CAB.DTNEG) BETWEEN P.DTINI AND P.DTFIN
        ),
        FLUXO_ITEM AS (
            SELECT R.NUNOTA, R.SEQUENCIA,
                   MIN(TRUNC(NVL(ITC.DTNEG, ITC.DTENTSAI))) DT_INICIO_COTACAO,
                   MAX(TRUNC(CAP.DTENTSAI)) DT_ATENDIMENTO
            FROM REQ_ITEM R
            LEFT JOIN TGFVAR VAR1 ON VAR1.NUNOTAORIG = R.NUNOTA AND VAR1.SEQUENCIAORIG = R.SEQUENCIA
            LEFT JOIN TGFCAB ITC ON ITC.NUNOTA = VAR1.NUNOTA
            LEFT JOIN TGFITE ITV ON ITV.NUNOTA = VAR1.NUNOTA AND ITV.SEQUENCIA = VAR1.SEQUENCIA
            LEFT JOIN TGFVAR VAR2 ON VAR2.NUNOTAORIG = ITC.NUNOTA AND VAR2.SEQUENCIAORIG = ITV.SEQUENCIA
            LEFT JOIN TGFCAB CAP ON CAP.NUNOTA = VAR2.NUNOTA
            GROUP BY R.NUNOTA, R.SEQUENCIA
        )
        SELECT
            R.NUNOTA,
            R.SEQUENCIA,
            CASE WHEN F.DT_ATENDIMENTO IS NOT NULL THEN 'Fechado'
                 WHEN F.DT_INICIO_COTACAO IS NOT NULL THEN 'Em andamento'
                 ELSE 'Aberto' END STATUS_REQUISICAO,
            TRUNC(NVL(F.DT_ATENDIMENTO, P.DTFIN)) - R.DT_INICIO_CALCULO DIAS_CALCULADOS,
            P.DIASPRAZO PRAZO_LIMITE
        FROM REQ_ITEM R
        INNER JOIN FLUXO_ITEM F ON F.NUNOTA = R.NUNOTA AND F.SEQUENCIA = R.SEQUENCIA
        CROSS JOIN PARAMS P
    )
)
SELECT
    COUNT(*) AS TOTAL_REQUISICOES_ITEM,
    SUM(CASE WHEN STATUS_REQUISICAO = 'Aberto' THEN 1 ELSE 0 END) AS TOTAL_ABERTAS,
    SUM(CASE WHEN STATUS_REQUISICAO = 'Em andamento' THEN 1 ELSE 0 END) AS TOTAL_EM_ANDAMENTO,
    SUM(CASE WHEN STATUS_REQUISICAO = 'Fechado' THEN 1 ELSE 0 END) AS TOTAL_FECHADAS,
    SUM(CASE WHEN DIAS_CALCULADOS <= PRAZO_LIMITE THEN 1 ELSE 0 END) AS TOTAL_NO_PRAZO,
    SUM(CASE WHEN DIAS_CALCULADOS > PRAZO_LIMITE THEN 1 ELSE 0 END) AS TOTAL_FORA_DO_PRAZO,
    ROUND((SUM(CASE WHEN DIAS_CALCULADOS <= PRAZO_LIMITE THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0)) * 100, 2) AS PERCENTUAL_NO_PRAZO,
    ROUND(AVG(DIAS_CALCULADOS), 2) AS LEAD_TIME_MEDIO
FROM BASE
