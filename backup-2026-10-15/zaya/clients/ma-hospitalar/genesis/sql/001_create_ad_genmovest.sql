-- Tabela de controle da integracao Sankhya x Genesis.
-- Estrutura alinhada aos campos criados no ambiente MA Hospitalar.

CREATE TABLE AD_GENMOVEST (
    IDINTGENESIS        NUMBER(10)      NOT NULL,
    CHAVE_MOVIMENTO     VARCHAR2(100)   NOT NULL,
    TIPO_MOVIMENTO      VARCHAR2(100)   NOT NULL,
    STATUS_INTEGRACAO   VARCHAR2(100)   DEFAULT 'PENDENTE' NOT NULL,
    TENTATIVAS          NUMBER(10)      DEFAULT 0 NOT NULL,
    HTTP_STATUS         NUMBER(10),
    MENSAGEM_ERRO       CLOB,
    PAYLOAD_HASH        VARCHAR2(100),
    PROTOCOLO_GENESIS   VARCHAR2(100),
    DH_INCLUSAO         DATE            DEFAULT SYSDATE NOT NULL,
    DH_ENVIO            DATE,
    DH_ATUALIZACAO      DATE,
    USU_REPROCESSAMENTO NUMBER(5),
    DH_REPROCESSAMENTO  DATE,
    NUNOTA              NUMBER(10),
    CONSTRAINT PK_AD_GENMOVEST PRIMARY KEY (IDINTGENESIS),
    CONSTRAINT UK_AD_GENMOVEST_CHAVE UNIQUE (CHAVE_MOVIMENTO)
);

CREATE INDEX IX_AD_GENMOVEST_STATUS
    ON AD_GENMOVEST (STATUS_INTEGRACAO, TENTATIVAS);

CREATE INDEX IX_AD_GENMOVEST_NUNOTA
    ON AD_GENMOVEST (NUNOTA);

-- Valores previstos para STATUS_INTEGRACAO:
-- PENDENTE, ENVIADO, ERRO, REPROCESSAR, IGNORADO.