-- AUDITORIA_IMPORTADOR_PEDIDOS.sql
-- Objetivo: diagnosticar divergencias de produto e rastrear por que itens nao foram para nota.
-- Banco esperado: Oracle (Sankhya)

--------------------------------------------------------------------------------
-- 1) DIAGNOSTICO BASE (COD x REFERENCIA x TGFPRO)
-- Use para identificar o tipo da divergencia na origem AD_IMPREGPED.
--------------------------------------------------------------------------------
SELECT
    A.PVX,
    A.EMPRESA,
    A.CODPARC,
    A.COD AS COD_IMPREGPED,
    A.REFERENCIA,
    PCOD.CODPROD AS COD_EXISTE_POR_COD,
    PREF.CODPROD AS COD_UNICO_POR_REFERENCIA,
    PREF.QTD_REF AS QTD_PRODUTOS_DA_REFERENCIA,
    CASE
        WHEN PCOD.CODPROD IS NULL AND NVL(PREF.QTD_REF,0) = 0 THEN 'SEM_PRODUTO_POR_COD_E_REFERENCIA'
        WHEN PCOD.CODPROD IS NULL AND PREF.QTD_REF = 1 THEN 'COD_INVALIDO_REFERENCIA_UNICA'
        WHEN PCOD.CODPROD IS NULL AND PREF.QTD_REF > 1 THEN 'COD_INVALIDO_REFERENCIA_AMBIGUA'
        WHEN PCOD.CODPROD IS NOT NULL AND NVL(PREF.QTD_REF,0) = 0 THEN 'COD_VALIDO_REFERENCIA_NAO_ENCONTRADA'
        WHEN PCOD.CODPROD IS NOT NULL AND PREF.QTD_REF = 1 AND PCOD.CODPROD <> PREF.CODPROD THEN 'COD_DIVERGENTE_DA_REFERENCIA'
        WHEN PCOD.CODPROD IS NOT NULL AND PREF.QTD_REF > 1 THEN 'REFERENCIA_AMBIGUA'
        ELSE 'CONSISTENTE'
    END AS DIAGNOSTICO
FROM AD_IMPREGPED A
LEFT JOIN TGFPRO PCOD
    ON PCOD.CODPROD = A.COD
LEFT JOIN (
    SELECT
        UPPER(TRIM(REFERENCIA)) AS REF_NORM,
        MIN(CODPROD) AS CODPROD,
        COUNT(*) AS QTD_REF
    FROM TGFPRO
    GROUP BY UPPER(TRIM(REFERENCIA))
) PREF
    ON PREF.REF_NORM = UPPER(TRIM(A.REFERENCIA))
WHERE A.PVX = :PVX
ORDER BY A.COD, A.REFERENCIA;

--------------------------------------------------------------------------------
-- 2) ITENS NA NOTA vs NAO FORAM (por NUNOTA)
--------------------------------------------------------------------------------
SELECT
    A.PVX,
    A.COD,
    A.REFERENCIA,
    P.CODPROD,
    I.NUNOTA,
    CASE
        WHEN P.CODPROD IS NULL THEN 'SEM_PRODUTO'
        WHEN I.CODPROD IS NULL THEN 'NAO_FOI_PRA_NOTA'
        ELSE 'OK_NA_NOTA'
    END AS STATUS
FROM AD_IMPREGPED A
LEFT JOIN TGFPRO P
    ON TRIM(UPPER(P.REFERENCIA)) = TRIM(UPPER(A.REFERENCIA))
LEFT JOIN TGFITE I
    ON I.CODPROD = P.CODPROD
   AND I.NUNOTA = :NUNOTA
WHERE A.PVX = :PVX
ORDER BY A.COD, A.REFERENCIA;

--------------------------------------------------------------------------------
-- 3) RASTREABILIDADE OPERACIONAL (logs por item)
-- Mostra evidencias de reconciliacao, erro tecnico e erro de negocio.
--------------------------------------------------------------------------------
SELECT
    L.DT_LOG,
    L.PVX,
    L.CODPROD,
    L.NUNOTA,
    L.STATUS_PROCESSO,
    CASE
        WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%RECONCILIACAO%' THEN 'RECONCILIACAO_PRODUTO'
        WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%ORIGEM: IMPORTADOR%' THEN 'ERRO_IMPORTADOR'
        WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%ORIGEM: SANKHYA%' THEN 'ERRO_SANKHYA'
        WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%COD_INVALIDO%' THEN 'COD_INVALIDO'
        WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%REFERENCIA_AMBIGUA%' THEN 'REFERENCIA_AMBIGUA'
        ELSE 'OUTRO'
    END AS CLASSE_LOG,
    L.MSG_ERRO
FROM AD_LOGIMPPEDCP L
WHERE L.PVX = :PVX
ORDER BY L.DT_LOG DESC;

--------------------------------------------------------------------------------
-- 4) RESUMO EXECUTIVO (contagem por classe de causa)
--------------------------------------------------------------------------------
WITH BASE AS (
    SELECT
        L.PVX,
        CASE
            WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%ERRO_USUARIO_PLANILHA%' THEN 'ERRO_USUARIO'
            WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%CADASTRO_PRODUTO%' THEN 'ERRO_CADASTRO_PRODUTO'
            WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%ORIGEM: SANKHYA%' THEN 'ERRO_TECNICO_SANKHYA'
            WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%ORIGEM: IMPORTADOR%' THEN 'ERRO_TECNICO_IMPORTADOR'
            WHEN UPPER(NVL(L.MSG_ERRO,'')) LIKE '%COD_CORRIGIDO%' THEN 'CORRIGIDO_AUTOMATICAMENTE'
            ELSE 'NAO_CLASSIFICADO'
        END AS CLASSE_CAUSA
    FROM AD_LOGIMPPEDCP L
    WHERE L.PVX = :PVX
)
SELECT
    PVX,
    CLASSE_CAUSA,
    COUNT(*) AS QTD
FROM BASE
GROUP BY PVX, CLASSE_CAUSA
ORDER BY QTD DESC;

--------------------------------------------------------------------------------
-- 5) ACAO RECOMENDADA (visao pronta para operacao)
--------------------------------------------------------------------------------
WITH D AS (
    SELECT
        A.PVX,
        A.COD,
        A.REFERENCIA,
        CASE
            WHEN PCOD.CODPROD IS NULL AND NVL(PREF.QTD_REF,0) = 0 THEN 'SEM_PRODUTO_POR_COD_E_REFERENCIA'
            WHEN PCOD.CODPROD IS NULL AND PREF.QTD_REF = 1 THEN 'COD_INVALIDO_REFERENCIA_UNICA'
            WHEN PCOD.CODPROD IS NULL AND PREF.QTD_REF > 1 THEN 'COD_INVALIDO_REFERENCIA_AMBIGUA'
            WHEN PCOD.CODPROD IS NOT NULL AND NVL(PREF.QTD_REF,0) = 0 THEN 'COD_VALIDO_REFERENCIA_NAO_ENCONTRADA'
            WHEN PCOD.CODPROD IS NOT NULL AND PREF.QTD_REF = 1 AND PCOD.CODPROD <> PREF.CODPROD THEN 'COD_DIVERGENTE_DA_REFERENCIA'
            WHEN PCOD.CODPROD IS NOT NULL AND PREF.QTD_REF > 1 THEN 'REFERENCIA_AMBIGUA'
            ELSE 'CONSISTENTE'
        END AS DIAGNOSTICO
    FROM AD_IMPREGPED A
    LEFT JOIN TGFPRO PCOD
        ON PCOD.CODPROD = A.COD
    LEFT JOIN (
        SELECT
            UPPER(TRIM(REFERENCIA)) AS REF_NORM,
            MIN(CODPROD) AS CODPROD,
            COUNT(*) AS QTD_REF
        FROM TGFPRO
        GROUP BY UPPER(TRIM(REFERENCIA))
    ) PREF
        ON PREF.REF_NORM = UPPER(TRIM(A.REFERENCIA))
    WHERE A.PVX = :PVX
)
SELECT
    PVX,
    COD,
    REFERENCIA,
    DIAGNOSTICO,
    CASE
        WHEN DIAGNOSTICO = 'CONSISTENTE' THEN 'SEM_ACAO'
        WHEN DIAGNOSTICO IN ('COD_INVALIDO_REFERENCIA_UNICA', 'COD_DIVERGENTE_DA_REFERENCIA') THEN 'REPROCESSAR (CORRIGE PELO CADASTRO)'
        WHEN DIAGNOSTICO IN ('SEM_PRODUTO_POR_COD_E_REFERENCIA', 'COD_VALIDO_REFERENCIA_NAO_ENCONTRADA') THEN 'AJUSTAR PLANILHA OU CADASTRO TGFPRO'
        WHEN DIAGNOSTICO IN ('REFERENCIA_AMBIGUA', 'COD_INVALIDO_REFERENCIA_AMBIGUA') THEN 'SANEAR CADASTRO (REFERENCIA DUPLICADA)'
        ELSE 'ANALISE_MANUAL'
    END AS ACAO_RECOMENDADA,
    CASE
        WHEN DIAGNOSTICO IN ('COD_INVALIDO_REFERENCIA_UNICA', 'COD_DIVERGENTE_DA_REFERENCIA') THEN 'ERRO_USUARIO_PLANILHA'
        WHEN DIAGNOSTICO IN ('REFERENCIA_AMBIGUA', 'COD_INVALIDO_REFERENCIA_AMBIGUA') THEN 'ERRO_CADASTRO_PRODUTO'
        WHEN DIAGNOSTICO IN ('SEM_PRODUTO_POR_COD_E_REFERENCIA', 'COD_VALIDO_REFERENCIA_NAO_ENCONTRADA') THEN 'PLANILHA_OU_CADASTRO'
        ELSE 'N/A'
    END AS CAUSA_PROVAVEL
FROM D
ORDER BY
    CASE WHEN DIAGNOSTICO = 'CONSISTENTE' THEN 2 ELSE 1 END,
    DIAGNOSTICO,
    COD;

--------------------------------------------------------------------------------
-- 6) INTEGRIDADE DE VALOR (QTY x UNITPRICE vs TOTALPRICE)
--------------------------------------------------------------------------------
SELECT
    A.PVX,
    A.COD,
    A.REFERENCIA,
    A.QTY,
    A.UNITPRICE,
    A.TOTALPRICE,
    (A.QTY * A.UNITPRICE) AS TOTAL_CALCULADO,
    CASE
        WHEN A.QTY IS NULL OR A.UNITPRICE IS NULL OR A.TOTALPRICE IS NULL THEN 'DADO_INCOMPLETO'
        WHEN (A.QTY * A.UNITPRICE) <> A.TOTALPRICE THEN 'DIVERGENTE'
        ELSE 'OK'
    END AS STATUS_TOTAL
FROM AD_IMPREGPED A
WHERE A.PVX = :PVX
ORDER BY STATUS_TOTAL DESC, A.COD;

--------------------------------------------------------------------------------
-- 7) MONITOR DE STATUS DO PIPELINE (JSON -> IMPREGPED -> NOTA)
--------------------------------------------------------------------------------
SELECT
    J.ID AS ID_JSON,
    J.PROCESSADO AS STATUS_JSON,
    COUNT(R.COD) AS QTD_ITENS_IMPORTADOS,
    SUM(CASE WHEN R.NUNOTA IS NOT NULL THEN 1 ELSE 0 END) AS QTD_ITENS_COM_NOTA,
    MIN(R.NUNOTA) AS NUNOTA_EXEMPLO
FROM AD_PRCSJSON J
LEFT JOIN AD_IMPREGPED R
    ON R.PVX IS NOT NULL
WHERE J.ID = :ID_JSON
GROUP BY J.ID, J.PROCESSADO;

