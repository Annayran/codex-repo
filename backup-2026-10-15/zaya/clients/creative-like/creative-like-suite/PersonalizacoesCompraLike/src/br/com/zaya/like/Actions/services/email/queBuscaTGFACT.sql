SELECT DISTINCT
   TPO.AD_MODELOEMAIL,
   USU.NOMEUSU AS REMETENTE, 
   DEST.EMAIL AS EMAILDESTINARIO,
   CAB.CODTIPOPER, 
   TPO.DESCROPER 
FROM   TGFCAB CAB  
    INNER JOIN TSIUSU USU ON USU.CODUSU = :CODUSU
    INNER JOIN TSIUSU DEST ON DEST.CODUSU = CAB.CODUSUINC
    INNER JOIN TGFTOP TPO ON CAB.CODTIPOPER = TPO.CODTIPOPER AND TPO.DHALTER = (select max(dhalter) from tgftop t where t.codtipoper = cab.codtipoper)
WHERE  NVL(AD_MODELOEMAIL,0) >0
AND CAB.NUNOTA = :NUNOTA
AND AD_NOTIFICAR_ACT = 'S'
