SELECT DISTINCT
    CAB.NUNOTA, 
    CAB.TIPMOV, 
    ITE.CODPROD, 
    ITE.SEQUENCIA,
    nullValue(ITE.AD_SEQUENCIAPNE ,ITE.SEQUENCIA) as AD_SEQUENCIAPNE
FROM TGFCAB CAB
INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
INNER JOIN (SELECT CAB2.TIPMOV,
                CAB2.AD_NUNEGOCIACAO, 
                ITE.CODPROD,
                ITE.SEQUENCIA,
                ITE.AD_SEQUENCIAPNE 
            FROM TGFCAB CAB2
            INNER JOIN TGFITE ITE ON CAB2.NUNOTA = ITE.NUNOTA
            WHERE CAB2.AD_NUNEGOCIACAO = :AD_NUNEGOCIACAO AND CAB2.TIPMOV = 'O') PEDCOMPRA ON ( PEDCOMPRA.AD_NUNEGOCIACAO = CAB.AD_NUNEGOCIACAO AND ITE.CODPROD = PEDCOMPRA.CODPROD)
WHERE CAB.AD_NUNEGOCIACAO = :AD_NUNEGOCIACAO AND CAB.TIPMOV = 'P'
AND ITE.CODPROD IN  :CODPROD
