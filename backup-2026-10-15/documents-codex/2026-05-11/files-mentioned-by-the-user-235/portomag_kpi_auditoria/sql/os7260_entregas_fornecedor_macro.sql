/* OS 7260 / Item 14 - KPI macro por fornecedor.
   Percentual on-time = entregas_no_prazo / total_entregas * 100.
*/
WITH DETALHE AS (
    SELECT *
    FROM (
        /* Substituir este bloco pela query os7260_entregas_fornecedor_detalhe.sql
           quando o componente Sankhya nao aceitar CTE compartilhada por arquivo. */
        WITH PARAMS AS (
            SELECT TRUNC(:PERIODO.INI) DTINI, TRUNC(:PERIODO.FIN) DTFIN FROM DUAL
        ),
        ENTREGA_ITEM AS (
            SELECT CAB.CODPARC, PAR.RAZAOSOCIAL, CAB.NUNOTA NUNOTA_PEDIDO, ITE.SEQUENCIA SEQ_PEDIDO,
                   ITC.NUNOTA NUNOTA_ENTRADA, ITV.SEQUENCIA SEQ_ENTRADA,
                   PRO.CODPROD, PRO.DESCRPROD, PRO.USOPROD,
                   TRUNC(NVL(ITE.DTINICIO, NVL(CAB.DTPREVENT, CAB.DTNEG))) DATA_PEDIDO,
                   TRUNC(ITC.DTENTSAI) DATA_ENTRADA,
                   CASE WHEN PRO.USOPROD = 'C' THEN 15 ELSE 30 END PRAZO_ESPERADO
            FROM TGFCAB CAB
            INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
            INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
            INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
            INNER JOIN TGFVAR VAR ON VAR.NUNOTAORIG = CAB.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA
            INNER JOIN TGFCAB ITC ON ITC.NUNOTA = VAR.NUNOTA
            INNER JOIN TGFITE ITV ON ITV.NUNOTA = VAR.NUNOTA AND ITV.SEQUENCIA = VAR.SEQUENCIA
            CROSS JOIN PARAMS P
            WHERE CAB.TIPMOV = 'O'
              AND TRUNC(ITC.DTENTSAI) BETWEEN P.DTINI AND P.DTFIN
              AND PAR.CODPARC = NVL(:CODPARC, PAR.CODPARC)
              AND PRO.USOPROD IN ('M', 'C')
            GROUP BY CAB.CODPARC, PAR.RAZAOSOCIAL, CAB.NUNOTA, ITE.SEQUENCIA, ITC.NUNOTA, ITV.SEQUENCIA,
                     PRO.CODPROD, PRO.DESCRPROD, PRO.USOPROD,
                     TRUNC(NVL(ITE.DTINICIO, NVL(CAB.DTPREVENT, CAB.DTNEG))), TRUNC(ITC.DTENTSAI)
        )
        SELECT
            CODPARC,
            RAZAOSOCIAL,
            NUNOTA_PEDIDO,
            SEQ_PEDIDO,
            NUNOTA_ENTRADA,
            SEQ_ENTRADA,
            DATA_ENTRADA - DATA_PEDIDO DIAS_CALCULADOS,
            PRAZO_ESPERADO,
            CASE WHEN DATA_ENTRADA - DATA_PEDIDO <= PRAZO_ESPERADO THEN 'S' ELSE 'N' END NOPRAZO
        FROM ENTREGA_ITEM
    )
)
SELECT
    CODPARC,
    RAZAOSOCIAL,
    COUNT(*) AS TOTAL_ENTREGAS,
    SUM(CASE WHEN NOPRAZO = 'S' THEN 1 ELSE 0 END) AS TOTAL_NO_PRAZO,
    SUM(CASE WHEN NOPRAZO = 'N' THEN 1 ELSE 0 END) AS TOTAL_FORA_DO_PRAZO,
    ROUND((SUM(CASE WHEN NOPRAZO = 'S' THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0)) * 100, 2) AS PERCENTUAL_ON_TIME,
    ROUND(AVG(DIAS_CALCULADOS), 2) AS LEAD_TIME_MEDIO,
    MIN(DIAS_CALCULADOS) AS MELHOR_PRAZO,
    MAX(DIAS_CALCULADOS) AS PIOR_PRAZO
FROM DETALHE
GROUP BY
    CODPARC,
    RAZAOSOCIAL
ORDER BY
    PERCENTUAL_ON_TIME DESC,
    TOTAL_ENTREGAS DESC,
    RAZAOSOCIAL
