/* OS 7259 / Item 13 - Lead Time de Requisicoes Atendidas
   Visao detalhada auditavel por requisicao/item.

   Periodo: usa TGFCAB.DTNEG da requisicao.
   Inicio do calculo: usa TGFCAB.DTENTSAI; se nulo, usa TGFCAB.DTNEG.
   Fim do calculo: usa data de atendimento final; se nao existir, usa :PERIODO.FIN.
   Historico: nao usa SYSDATE, evitando mudanca de resultado em meses fechados.
   TOPs: 400 e 401 conforme levantamento. Se o cliente confirmar outra TOP, ajustar na CTE PARAMS.
*/
WITH PARAMS AS (
    SELECT
        TRUNC(:PERIODO.INI) AS DTINI,
        TRUNC(:PERIODO.FIN) AS DTFIN,
        NVL(:DIASPRAZO, 7) AS DIASPRAZO
    FROM DUAL
),
REQ_ITEM AS (
    SELECT
        CAB.NUNOTA,
        ITE.SEQUENCIA,
        CAB.CODTIPOPER,
        TOP.DESCROPER,
        ITE.CODPROD,
        PRO.DESCRPROD,
        TRUNC(CAB.DTNEG) AS DT_REQUISICAO,
        TRUNC(NVL(CAB.DTENTSAI, CAB.DTNEG)) AS DT_INICIO_CALCULO
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE
        ON ITE.NUNOTA = CAB.NUNOTA
    INNER JOIN TGFTOP TOP
        ON TOP.CODTIPOPER = CAB.CODTIPOPER
       AND TOP.DHALTER = CAB.DHTIPOPER
    INNER JOIN TGFPRO PRO
        ON PRO.CODPROD = ITE.CODPROD
    CROSS JOIN PARAMS P
    WHERE CAB.CODTIPOPER IN (400, 401)
      AND TRUNC(CAB.DTNEG) BETWEEN P.DTINI AND P.DTFIN
),
FLUXO_ITEM AS (
    SELECT
        R.NUNOTA,
        R.SEQUENCIA,
        MIN(TRUNC(NVL(ITC.DTNEG, ITC.DTENTSAI))) AS DT_INICIO_COTACAO,
        MAX(TRUNC(CAP.DTENTSAI)) AS DT_ATENDIMENTO,
        MAX(ITC.NUNOTA) AS NUNOTA_COTACAO,
        MAX(CAP.NUNOTA) AS NUNOTA_ATENDIMENTO
    FROM REQ_ITEM R
    LEFT JOIN TGFVAR VAR1
        ON VAR1.NUNOTAORIG = R.NUNOTA
       AND VAR1.SEQUENCIAORIG = R.SEQUENCIA
    LEFT JOIN TGFCAB ITC
        ON ITC.NUNOTA = VAR1.NUNOTA
    LEFT JOIN TGFITE ITV
        ON ITV.NUNOTA = VAR1.NUNOTA
       AND ITV.SEQUENCIA = VAR1.SEQUENCIA
    LEFT JOIN TGFVAR VAR2
        ON VAR2.NUNOTAORIG = ITC.NUNOTA
       AND VAR2.SEQUENCIAORIG = ITV.SEQUENCIA
    LEFT JOIN TGFCAB CAP
        ON CAP.NUNOTA = VAR2.NUNOTA
    GROUP BY
        R.NUNOTA,
        R.SEQUENCIA
),
DETALHE AS (
    SELECT
        R.NUNOTA,
        R.SEQUENCIA,
        R.CODTIPOPER,
        R.DESCROPER,
        R.CODPROD,
        R.DESCRPROD,
        R.DT_REQUISICAO,
        F.DT_INICIO_COTACAO,
        F.DT_ATENDIMENTO,
        P.DTFIN AS DT_CORTE_USADA,
        F.NUNOTA_COTACAO,
        F.NUNOTA_ATENDIMENTO,
        CASE
            WHEN F.DT_ATENDIMENTO IS NOT NULL THEN 'Fechado'
            WHEN F.DT_INICIO_COTACAO IS NOT NULL THEN 'Em andamento'
            ELSE 'Aberto'
        END AS STATUS_REQUISICAO,
        TRUNC(NVL(F.DT_ATENDIMENTO, P.DTFIN)) - R.DT_INICIO_CALCULO AS DIAS_CALCULADOS,
        P.DIASPRAZO AS PRAZO_LIMITE
    FROM REQ_ITEM R
    INNER JOIN FLUXO_ITEM F
        ON F.NUNOTA = R.NUNOTA
       AND F.SEQUENCIA = R.SEQUENCIA
    CROSS JOIN PARAMS P
)
SELECT
    NUNOTA,
    SEQUENCIA,
    CODTIPOPER,
    DESCROPER,
    CODPROD,
    DESCRPROD,
    DT_REQUISICAO,
    DT_INICIO_COTACAO,
    DT_ATENDIMENTO,
    DT_CORTE_USADA,
    NUNOTA_COTACAO,
    NUNOTA_ATENDIMENTO,
    DIAS_CALCULADOS,
    PRAZO_LIMITE,
    STATUS_REQUISICAO,
    CASE
        WHEN DIAS_CALCULADOS <= PRAZO_LIMITE THEN 'No Prazo'
        ELSE 'Fora do Prazo'
    END AS CLASSIFICACAO_PRAZO
FROM DETALHE
ORDER BY
    DT_REQUISICAO,
    NUNOTA,
    SEQUENCIA
